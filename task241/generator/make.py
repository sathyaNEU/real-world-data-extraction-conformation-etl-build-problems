"""Build the pack, compute every owed figure, write the goldens, figures.json, submission.md and metadata.json, run the
checks and the independent verifier, rebuild into a scratch folder and require byte-identical output, then cut
target.zip.

    python3 task241/generator/make.py            (full: two builds, the zip)
    python3 task241/generator/make.py --once     (one build, no zip)
"""
import hashlib
import json
import os
import shutil
import sys
import tempfile
import time
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B
import golden as GD
import solve as SV
import writeup as WU

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
STAMP = (2027, 1, 15, 8, 0, 0)         # the morning the pack was drawn
AS_OF = "2027-01-15"


def walk(folder):
    out = []
    for root, _, files in os.walk(folder):
        for f in files:
            out.append(os.path.relpath(os.path.join(root, f), folder))
    return sorted(out)


def metadata(target):
    files = []
    for rel in walk(target):
        p = os.path.join(target, rel)
        rows = sum(1 for _ in open(p, encoding="utf-8")) - 1 if rel.endswith(".csv") else None
        files.append({"path": rel, "format": rel.rsplit(".", 1)[1], "bytes": os.path.getsize(p), "rows": rows,
                      "source": "Constructed (seeded generator, task241/generator/make.py)", "date": AS_OF,
                      "license": "CC0-1.0 (original work)"})
    big = max((x for x in files if x["rows"]), key=lambda x: x["rows"])
    meta = {
        "task": "task241",
        "title": "Which of a survey research firm's recurring telephone projects open the 2027 project year with the "
                 "dialer's answering machine detection switched off, from each project's 2026 share of machine-classed "
                 "calls that a person had answered, against the firm's one-in-ten limit",
        "domain": "General Statistics & Data Science",
        "subdomain": "missing-data-censoring-measurement-error (a recorded classification's error rate, per project, "
                     "for a telephone centre's 2027 dialer settings)",
        "objective": "Data Quality Monitoring & Alerting",
        "prompt_shape": "10: scorecard, each recurring project's 2026 share of machine-classed calls answered by a person "
                        "and its detection verdict against the one-in-ten limit, with each project's calling-hours "
                        "exceptions, completed interviews and interviewer hours, and a one-page note",
        "as_of": AS_OF,
        "deliverables": [GD.XLSX, GD.PDF],
        "distractor_files": [B.FILES[k] for k in B.DISTRACTORS],
        "stated_inputs": ["9", "10", "20", "40", "5", "8", "21"],
        "field_terms": [],
        "input_gates": {"files": len(files), "formats": sorted({x["format"] for x in files}),
                        "largest_file": big["path"], "largest_file_rows": big["rows"]},
        "sources": [{"files": "all files under target/",
                     "origin": "generated by task241/generator/make.py (seeded, deterministic) around an independent "
                               "survey research firm's telephone centre: its predictive dialer's monthly call detail "
                               "exports, the inbound switch's call log, the client case records, a state time zone list, "
                               "the 2027 project setup register, the 2027 dialer policy, the detection maker's release "
                               "sheet, the 2025 listening audit, the client invoices, the payroll's interviewer hours, a "
                               "mobile consent log and the quality monitoring scores; the firm, its clients, the maker "
                               "and the people are invented, and the calls are simulated, not taken from any real "
                               "dataset.",
                     "date": AS_OF, "license": "CC0-1.0 (original work)"}],
        "created": "2026-11-03",
        "generator": "task241/generator/make.py",
        "files": files,
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def stamp(folder):
    t = time.mktime((*STAMP, 0, 0, -1))
    for rel in walk(folder):
        os.utime(os.path.join(folder, rel), (t, t))


def digest(folder):
    return {rel: hashlib.sha256(open(os.path.join(folder, rel), "rb").read()).hexdigest() for rel in walk(folder)}


def cut_zip():
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for d in sorted({os.path.dirname(r) for r in walk(TARGET) if os.path.dirname(r)}):
            zi = zipfile.ZipInfo(d + "/", date_time=STAMP)
            zi.external_attr = (0o40755 << 16) | 0x10
            z.writestr(zi, b"")
        for rel in walk(TARGET):
            zi = zipfile.ZipInfo(rel, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TARGET, rel), "rb").read())
    return zp


def fresh(folder):
    shutil.rmtree(folder, ignore_errors=True)
    os.makedirs(folder, exist_ok=True)


def main(second=True, checks=True):
    fresh(TARGET)
    W = B.run(TARGET)
    stamp(TARGET)
    S = SV.solve(TARGET)
    A = WU.answers(S)
    fresh(GOLDEN)
    GD.write(GOLDEN, A)
    stamp(GOLDEN)
    fig = WU.write(TASK, HERE, A)
    metadata(TARGET)
    if checks:
        import checks as C
        n = C.run(TARGET, GOLDEN, W, S, A)
        for line in C.LOG:
            print("  " + line)
        print("checks: %d passed" % n)
        import verify as V
        V.main(TARGET, GOLDEN, os.path.join(HERE, "figures.json"), os.path.join(TASK, "submission.md"))
    if second:
        tmp = tempfile.mkdtemp(dir=os.environ.get("TMPBUILD"))
        t2, g2 = os.path.join(tmp, "target"), os.path.join(tmp, "golden")
        B.run(t2)
        stamp(t2)
        GD.write(g2, WU.answers(SV.solve(t2)))
        stamp(g2)
        d1, d2 = digest(TARGET), digest(t2)
        assert d1 == d2, [f for f in d1 if d1[f] != d2.get(f)]
        g1, g2d = digest(GOLDEN), digest(g2)
        assert g1 == g2d, ("golden differs between builds", [f for f in g1 if g1[f] != g2d.get(f)])
        shutil.rmtree(tmp)
        zp = cut_zip()
        print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
    return A, fig


if __name__ == "__main__":
    main(second="--once" not in sys.argv, checks="--nochecks" not in sys.argv)
