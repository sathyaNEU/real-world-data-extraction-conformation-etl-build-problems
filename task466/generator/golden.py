MON = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def round_to(v, unit):
    return int(unit * round(v / unit))


def compute(target):
    r = A.compute(target)
    g = r["call"]
    r["released_10"] = round_to(g["golden_rel"], 10)
    r["generated_100"] = round_to(g["steady_gen"], 100)
    r["captured_1"] = int(round(g["captured"]))
    r["hh8_rel_1"] = int(round(g["hh8_rel"]))
    r["naive_rel_1"] = int(round(g["naive_rel"]))
    return r


def chart_png(res):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    rel = res["call"]["golden_rel"]
    ink, muted = "#1f2a33", "#5b6670"
    fig, ax = plt.subplots(figsize=(7.0, 2.35), dpi=160)
    for lo, hi, col in ((0, 375, "#f3efe6"), (375, 450, "#ead9bb"), (450, 560, "#dfc197")):
        ax.axvspan(lo, hi, color=col, lw=0)
    ax.barh([0], [rel], height=0.34, color="#2f5d8a")
    for x in (375, 450):
        ax.axvline(x, color=muted, lw=0.9, ls=(0, (4, 3)))
        ax.text(x - 4, 0.47, "%d t" % x, ha="right", va="bottom", fontsize=7.5, color=muted)
    ax.text(187, 0.30, "Tier 1\nno charge", ha="center", va="center", fontsize=7.5, color=ink)
    ax.text(412.5, 0.30, "Tier 2\n$118,000", ha="center", va="center", fontsize=7.5, color=ink)
    ax.text(505, 0.30, "Tier 3\n$312,000\nand a plan", ha="center", va="center", fontsize=7.5, color=ink)
    ax.text(rel - 6, 0, "%d t" % res["released_10"], ha="right", va="center", fontsize=8.5, color="white",
            fontweight="bold")
    ax.set_xlim(0, 560)
    ax.set_ylim(-0.32, 0.62)
    ax.set_yticks([])
    ax.set_xticks(range(0, 600, 100))
    ax.set_xlabel("Methane released in 2026 (tonnes)", fontsize=8, color=muted)
    ax.tick_params(axis="x", labelsize=7.5, colors=muted, length=3)
    ax.set_title("Breck Hollow released about %d t of methane in 2026, inside Tier 2" % res["released_10"],
                 fontsize=9, color=ink, loc="left")
    for s in ("top", "right", "left"):
        ax.spines[s].set_visible(False)
    ax.spines["bottom"].set_color("#9aa3ab")
    fig.tight_layout()
    buf = io.BytesIO()
    fig.savefig(buf, format="png", metadata={"Software": None})
    plt.close(fig)
    return buf.getvalue()


def write_brief(res, path):
    from reportlab.lib.pagesizes import letter
    from reportlab.lib.units import mm
    from reportlab.lib.utils import ImageReader
    from reportlab.pdfgen import canvas
    import textwrap
    C.pdf_canvas_settings()
    g = res["call"]
    c = canvas.Canvas(path, pagesize=letter, invariant=1)
    c.setTitle("Breck Hollow methane charge 2026")
    c.setAuthor("Bianca Erickson")
    c.setCreator("")
    y = 262 * mm
    L = 18 * mm

    def para(text, size=9.5, bold=False, gap=4.6, width=98, after=1.6):
        nonlocal y
        c.setFont("Helvetica-Bold" if bold else "Helvetica", size)
        for ln in textwrap.wrap(text, width):
            c.drawString(L, y, ln)
            y -= gap * mm
        y -= after * mm

    para("Quarrow Valley Regional Solid Waste Authority", 11, True, after=0.6)
    para("Environmental Compliance", 9, after=2.4)
    para("To: Finance Committee     From: Bianca Erickson, Environmental Compliance     Date: 15 January 2027", 9)
    para("Breck Hollow's 2026 methane return falls in Tier 2: carry $118,000 in the 2027 budget", 10.5, True)
    para("Breck Hollow Landfill released about %d tonnes of methane in 2026, %d t above the Tier 2 threshold of the "
         "state's closed landfill methane charge and %d t below Tier 3. The charge is $118,000, which the Department "
         "invoices by 30 June 2027; no corrective action plan is triggered."
         % (res["released_10"], res["released_10"] - 375, 450 - res["released_10"]))
    # the three return figures
    c.setFont("Helvetica-Bold", 8.5)
    c.drawString(L, y, "2026 return, tonnes of methane")
    y -= 4.4 * mm
    c.setFont("Helvetica", 8.5)
    for label, val in (("Captured by the gas system", "{:,}".format(res["captured_1"])),
                       ("Generated by the waste (nearest 100 t)", "{:,}".format(res["generated_100"])),
                       ("Released (nearest 10 t)", "{:,}".format(res["released_10"]))):
        c.drawString(L + 3 * mm, y, label)
        c.drawRightString(L + 96 * mm, y, val)
        y -= 4.2 * mm
    c.setFont("Helvetica-Oblique", 7.5)
    c.drawString(L, y, "Source: gas plant historian and outage log, 2026; DEQ Closed Landfill Methane Rule, Schedule 2.")
    y -= 3.0 * mm
    png = chart_png(res)
    img = ImageReader(io.BytesIO(png))
    c.drawImage(img, L, y - 56 * mm, width=170 * mm, height=56 * mm)
    y -= 61 * mm
    para("How the figure was built", 10, True)
    para("The gas plant captured %s t of methane in 2026: the historian's hourly flows at normal conditions times the "
         "measured methane content, over the local calendar year.(1) The rule has us estimate what the waste generated "
         "from that capture at the 0.90 collection efficiency for our geomembrane cap. The blowers were down %d times "
         "for %.1f hours in all, and after each restart the wells drew off gas the waste had held during the stop, "
         "%d t over the year on top of the steady capture. That gas was generated during the outages, so generation is "
         "read from the steady hours, month by month: about %s t for the year. Released methane is the uncaptured part "
         "less 10 per cent oxidised in the cap, plus 1 per cent of the captured gas not destroyed in the engines and flare."
         % ("{:,}".format(res["captured_1"]), g["n_outages"], g["down_hours"], round(g["recovered"]),
            "{:,}".format(res["generated_100"])))
    para("Scaling the year's capture up by the share of hours the blowers ran, without taking out the gas recovered "
         "after restarts, would count that gas twice and put us at %d t, in Tier 3. Dividing the capture by 0.90 with "
         "no allowance for the outages would put us at %d t, in Tier 1. Neither matches the plant record."
         % (res["hh8_rel_1"], res["naive_rel_1"]))
    para("The return workbook (breck_hollow_methane_return_2026.xlsx) carries the engine and flare hours, engine starts, "
         "flare methane and surface monitoring results for the return, which is due by 31 March.", 9)
    c.setFont("Helvetica", 7.5)
    c.drawString(L, 24 * mm, "(1) The reporting year is the calendar year in local time (rule 1.1); the historian records "
                             "in UTC, so the year runs from 06:00 UTC on 1 January.")
    c.setStrokeColorRGB(0.6, 0.6, 0.6)
    c.line(L, 17 * mm, L + 176 * mm, 17 * mm)
    c.drawString(L, 13 * mm, "Quarrow Valley Regional Solid Waste Authority, Environmental Compliance")
    c.drawRightString(L + 176 * mm, 13 * mm, "Page 1 of 1")
    c.showPage()
    c.save()


def write_workbook(res, path):
    import openpyxl
    from openpyxl.styles import Font, Alignment
    wb = openpyxl.Workbook()
    g = res["call"]
    ws = wb.active
    ws.title = "Return 2026"
    bold = Font(bold=True)
    rows = [("Breck Hollow Landfill - Closed Landfill Methane Rule return, reporting year 2026", None, None),
            (None, None, None),
            ("Item", "Value", "Format"),
            ("Methane generated (t, nearest 100)", res["generated_100"], "#,##0"),
            ("Methane captured (t)", res["captured_1"], "#,##0"),
            ("Methane released (t, nearest 10)", res["released_10"], "#,##0"),
            ("Charge tier (rule 5.1)", res["tier"], None),
            ("Charge payable in 2027 ($)", res["charge"], "$#,##0"),
            (None, None, None),
            ("Basis", None, None),
            ("Collection efficiency (Schedule 2, geomembrane cap)", 0.90, "0.00"),
            ("Fraction of uncaptured methane oxidised in the cap", 0.10, "0.00"),
            ("Destruction efficiency, engines and enclosed flare", 0.99, "0.00"),
            ("Blower outages in 2026 (number)", g["n_outages"], "0"),
            ("Hours the gas system was down in 2026", round(g["down_hours"], 2), "#,##0.00"),
            ("Methane recovered after restarts, generated during outages (t)", round(g["recovered"], 1), "#,##0.0")]
    for i, (a, b, fmt) in enumerate(rows, start=1):
        ws.cell(row=i, column=1, value=a)
        cl = ws.cell(row=i, column=2, value=b)
        if fmt:
            cl.number_format = fmt
            cl.alignment = Alignment(horizontal="right")
    for ref in ("A1", "A3", "B3", "A10"):
        ws[ref].font = bold
    ws.column_dimensions["A"].width = 62
    ws.column_dimensions["B"].width = 16

    ws2 = wb.create_sheet("Destruction devices")
    ws2.append(["Quarter", "Engine 1 operating hours", "Engine 1 starts", "Engine 2 operating hours", "Engine 2 starts",
                "Flare operating hours", "Methane destroyed in flare (t)"])
    for cl in ws2[1]:
        cl.font = bold
        cl.alignment = Alignment(wrap_text=True, vertical="top")
    tot = [0.0] * 6
    for q in (1, 2, 3, 4):
        e1, e2, fl = res["engines"][(1, q)], res["engines"][(2, q)], res["flare"][q]
        vals = [e1["hours"], e1["starts"], e2["hours"], e2["starts"], fl["hours"], fl["destroyed"]]
        tot = [a + b for a, b in zip(tot, vals)]
        ws2.append(["Q%d 2026" % q] + [int(round(v)) for v in vals])
    ws2.append(["2026"] + [int(round(v)) for v in tot])
    for cl in ws2[6]:
        cl.font = bold
    for row in ws2.iter_rows(min_row=2, min_col=2):
        for cl in row:
            cl.number_format = "#,##0"
    for col in "ABCDEFG":
        ws2.column_dimensions[col].width = 15
    ws2.row_dimensions[1].height = 30
    ws2.freeze_panes = "B2"
    ws2.print_title_rows = "1:1"

    ws3 = wb.create_sheet("Surface monitoring")
    ws3.append(["Walkover", "Exceedance locations", "Of those, still exceedances at first re-monitoring"])
    for cl in ws3[1]:
        cl.font = bold
        cl.alignment = Alignment(wrap_text=True, vertical="top")
    for q in (1, 2, 3, 4):
        s = res["sem"][q]
        ws3.append(["Q%d 2026" % q, s["exceed"], s["still"]])
    ws3.append(["2026", sum(res["sem"][q]["exceed"] for q in (1, 2, 3, 4)), sum(res["sem"][q]["still"] for q in (1, 2, 3, 4))])
    for cl in ws3[6]:
        cl.font = bold
    for col, w in zip("ABC", (12, 22, 30)):
        ws3.column_dimensions[col].width = w
    ws3.row_dimensions[1].height = 30
    ws3.freeze_panes = "B2"

    ws4 = wb.create_sheet("Generation working")
    ws4.append(["Month (local)", "Steady capture (kg CH4/h)", "Hours", "Methane generated (t)"])
    for cl in ws4[1]:
        cl.font = bold
        cl.alignment = Alignment(wrap_text=True, vertical="top")
    gen_tot, h_tot = 0.0, 0
    for m in g["months"]:
        gm = m["steady_rate"] / 0.90 * m["hours"] / 1000.0
        gen_tot += gm
        h_tot += int(m["hours"])
        ws4.append([MON[m["month"] - 1] + " 2026", round(m["steady_rate"], 1), int(m["hours"]), round(gm, 1)])
    ws4.append(["2026 (before rounding)", None, h_tot, round(gen_tot, 1)])
    for cl in ws4[ws4.max_row]:
        cl.font = bold
    for row in ws4.iter_rows(min_row=2, min_col=2):
        for k, cl in enumerate(row):
            cl.number_format = ("#,##0.0", "#,##0", "#,##0.0")[k]
    for col, w in zip("ABCD", (24, 18, 10, 16)):
        ws4.column_dimensions[col].width = w
    ws4.row_dimensions[1].height = 30
    ws4.freeze_panes = "A2"

    ws5 = wb.create_sheet("Notes")
    notes = [
        "Prepared 15 January 2027 by Environmental Compliance for the 2026 return under the Closed Landfill Methane "
        "Rule, due by 31 March 2027.",
        "Reporting year and quarters: calendar, in local time (rule 1.1). The historian records in UTC.",
        "Methane captured: each hour's FT-101 flow at normal conditions times its AT-101 methane content, at 0.7168 kg "
        "per normal cubic metre (rule 1.3).",
        "Methane generated: the steady capture (full running hours outside the blower outages and the recovery after "
        "each restart) over 0.90, Schedule 2's collection efficiency for the geomembrane cap, for every hour of the "
        "year (rules 1.2 and 4.1). The return reports it to the nearest 100 t.",
        "Methane released: rule 1.6, with 0.10 of the uncaptured methane oxidised in the cap and 0.99 destruction "
        "efficiency in the engines and the enclosed flare.",
        "Engine operating hours: synchronised elapsed time (rule 1.7). Starts: each start from standstill (rule 1.8), "
        "including a mechanic's test run off the grid; a re-synchronisation after a breaker opening is not a start.",
        "Flare: operating hours at or above 1,400 F; methane routed by difference at the plant (FT-101 less FT-201 "
        "and FT-202), times 0.99.",
        "Surface monitoring: an exceedance is a reading more than 500 ppm above background (plan 7.2). Third-quarter "
        "readings taken on 15 September between the morning check and the failed midday check are void (plan 7.3).",
        "Sources: BH_gas_plant_hourly_2024-2026.csv, BH_gas_plant_outage_log_2024-2026.xlsx, "
        "BH_engine_plant_events_2026.txt, BH_surface_emissions_monitoring_2026.xlsx, SEM_analyser_checks_2026.csv, "
        "BH_site_register_2025.xlsx.",
    ]
    ws5.append(["Notes"])
    ws5["A1"].font = bold
    for n in notes:
        ws5.append([n])
        ws5.cell(row=ws5.max_row, column=1).alignment = Alignment(wrap_text=True, vertical="top")
    ws5.column_dimensions["A"].width = 110
    C.save_workbook(wb, path, dt.datetime(2027, 1, 15, 9, 30), "Quarrow Valley Regional Solid Waste Authority")


def write_golden(target, golden_dir):
    if not os.path.isdir(golden_dir):
        os.makedirs(golden_dir)
    res = compute(target)
    write_brief(res, os.path.join(golden_dir, "breck_hollow_charge_brief_2026.pdf"))
    write_workbook(res, os.path.join(golden_dir, "breck_hollow_methane_return_2026.xlsx"))
    return res


def figures(res):
    g = res["call"]
    f = {
        "tier": res["tier"], "charge_usd": res["charge"],
        "released_t_nearest_10": res["released_10"], "generated_t_nearest_100": res["generated_100"],
        "captured_t": res["captured_1"],
        "released_t_unrounded": round(g["golden_rel"], 1), "generated_t_unrounded": round(g["steady_gen"], 1),
        "recovered_after_restarts_t": round(g["recovered"], 1), "outages_n": g["n_outages"],
        "down_hours": round(g["down_hours"], 2), "running_share": round(g["f_rec"], 4),
        "default_hh8_generated_t": round(g["hh8_gen"], 1), "default_hh8_released_t": res["hh8_rel_1"],
        "naive_released_t": res["naive_rel_1"], "naive_generated_t": round(g["naive_gen"], 1),
        "threshold_tier2_t": 375, "threshold_tier3_t": 450, "charge_tier3_usd": 312000,
        "ce": 0.90, "ox": 0.10, "de": 0.99, "rho_n": 0.7168,
        "sem_threshold_ppm": 500, "sem_reading_threshold_ppm": 503,
        "clauses": ["1.1", "1.3", "1.2", "1.6", "1.7", "1.8", "5.1", "1.5", "7.3"],
    }
    for q in (1, 2, 3, 4):
        for e in (1, 2):
            f["engine%d_hours_q%d" % (e, q)] = int(round(res["engines"][(e, q)]["hours"]))
            f["engine%d_starts_q%d" % (e, q)] = res["engines"][(e, q)]["starts"]
        f["flare_hours_q%d" % q] = int(round(res["flare"][q]["hours"]))
        f["flare_destroyed_t_q%d" % q] = int(round(res["flare"][q]["destroyed"]))
        f["sem_exceed_q%d" % q] = res["sem"][q]["exceed"]
        f["sem_still_q%d" % q] = res["sem"][q]["still"]
    return f
