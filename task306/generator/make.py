"""Build the pack, compute every owed figure from it, write the goldens, figures.json, submission.md and metadata.json,
run the checks, rebuild into a scratch folder and require byte-identical output, cut target.zip and run the independent
verifier on it.

    python3 task306/generator/make.py            (full: two builds, the zip, the verifier)
    python3 task306/generator/make.py --once     (one build, no zip)
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B
import figs as FG
import golden as GD
import params as P
import writeup as WU

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
STAMP = (2026, 8, 14, 15, 40, 0)        # the afternoon the planning folder was put together


