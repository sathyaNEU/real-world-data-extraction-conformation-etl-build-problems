"""Build the dataset, write metadata.json, run the checks, rebuild into a scratch folder and require byte-identical
output, then cut target.zip. Dataset only: no prompt, no golden, no stump.

    python3 task112_ext/generator/make.py            (full: two builds, the zip)
    python3 task112_ext/generator/make.py --once     (one build, no zip)
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import docs
import params as P
import records as RC
import world as W

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
STAMP = (2028, 1, 12, 8, 0, 0)        # the morning the folder was put together


def build(target):
    w = W.World()
    p = lambda k: os.path.join(target, RC.FILES[k])
    rows = RC.write_all(w, target)
    docs.calendar(p("calendar"))
    docs.policy(p("policy"))
    docs.media_plan(p("mediaplan"))
    docs.dictionary(p("dictionary"))
    docs.manifest(p("manifest"), rows)
    rows["manifest"] = len(docs.MANIFEST)
    return w, rows


