"""task213 build: world -> overlays -> pack -> golden figures -> deliverables -> metadata -> target.zip.

    python3 task213/generator/build.py [--seed N] [--no-zip]
"""
import json, os, shutil, sys, zipfile
from pathlib import Path
HERE = Path(__file__).resolve().parent
TASK = HERE.parent
sys.path.insert(0, str(HERE))
import numpy as np
import core, extras, render, docs, golden

SEED = 3


def world(seed):
    w = core.gen(seed)
    x = extras.extras(w, seed)
    d = dict(w); d['X'] = x['X']; d['T'] = x['T']; d['A'] = x['A']
    return w, x, d


def figures(w, x, d):
    mc = golden.main_call(d, x, x['handle_now'])
    dis = golden.ask_disputes(x)
    onc = golden.ask_onchain(x)
    cbk, _ = golden.ask_cashback(w, x)
    F = dict(call=dict(expunged_exact=mc['expunged'], notice=mc['notice'], ratings_given=mc['given'], held=mc['held'],
                       accounts_suspended=mc['accounts'], rings=len(mc['lines'])),
             rings=[{k: v for k, v in r.items() if k != 'members'} for r in mc['lines']],
             disputes={k: v for k, v in dis.items()},
             onchain={k: dict(withdrawn=int(round(v['withdrawn'])), fees=int(round(v['fees']))) for k, v in onc.items()},
             cashback={k: dict(cashback=int(round(v['cashback'])), buyers=v['buyers']) for k, v in cbk.items()},
             raw=dict(onchain=onc, cashback=cbk),
             rivals=dict(default_exact=None, default_notice=None, q2_notice=9800, q2_ratings=181400, prevalence_pct=5.3,
                         q2_scaled=int(round(9800 * len(d['R'][d['R'].t < core.Q]) / 181400)),
                         prevalence_scaled=int(round(0.053 * len(d['R'][d['R'].t < core.Q])))))
    import screens
    dflt = screens.readers_default(d, w)
    F['rivals']['default_exact'] = dflt; F['rivals']['default_notice'] = int(round(dflt, -2))
    F['refs'] = dict(playbook_clauses=['1.2', '3.1', '3.3'], desk_procedure_clause='1.2', notice_date='1 December 2026', request_limit_usdt=1000)
    return F, mc


def write_metadata(target):
    files = sorted(p.name for p in target.iterdir())
    meta = dict(task='task213', setting_date='2026-11-05', synthetic=True, license='CC BY 4.0',
                source='synthetic, generated by task213/generator/build.py from one seed; invented organisations and people',
                files=[dict(name=n, bytes=(target / n).stat().st_size, source='synthetic (task213 generator)',
                            date='2026-10-06', license='CC BY 4.0') for n in files],
                distractors=[
                    dict(file='transparency_report_2026q2.pdf', basis='wrong-basis',
                         ruled_out_by='the report defines prevalence as every inauthentic rating in a labelled sample (paid, '
                                      'coerced, retaliatory, fake-account and ring ratings) and says the Q3 sample is not '
                                      'labelled until January 2027'),
                    dict(file='integrity_notices_2026.pdf', basis='wrong-basis',
                         ruled_out_by='each notice counts the ratings given in its own quarter by the rings that quarter\'s '
                                      'sweep found; the playbook (3.1) sweeps the ratings given in the quarter swept')],
                deliverables=['q3_ratings_sweep.xlsx', 'q3_sweep_chart.png'])
    (TASK / 'metadata.json').write_text(json.dumps(meta, indent=2) + '\n')


def cut_zip(target):
    zp = TASK / 'target.zip'
    with zipfile.ZipFile(zp, 'w', zipfile.ZIP_DEFLATED) as z:
        for p in sorted(target.iterdir()):
            zi = zipfile.ZipInfo('target/' + p.name, date_time=(2026, 11, 5, 9, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, p.read_bytes())


def main(argv):
    seed = SEED
    if '--seed' in argv: seed = int(argv[argv.index('--seed') + 1])
    target = TASK / 'target'
    if target.exists(): shutil.rmtree(target)
    target.mkdir()
    w, x, d = world(seed)
    ro = render.render(w, x, seed, target)
    docs.write_documents(target, w, x, ro)
    F, mc = figures(w, x, d)
    F['seed'] = seed
    (HERE / 'figures.json').write_text(json.dumps(F, indent=1) + '\n')
    if '--no-deliverables' not in argv:
        import deliverables
        deliverables.write_all(F, TASK)
    write_metadata(target)
    if '--no-zip' not in argv:
        cut_zip(target)
    return w, x, d, ro, F, mc


if __name__ == '__main__':
    main(sys.argv[1:])
