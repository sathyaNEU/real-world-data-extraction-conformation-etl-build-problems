"""Build the pack, compute every owed figure from it, write the goldens, figures.json, submission.md and metadata.json, run
the checks and the independent verifier, rebuild into a scratch folder and require byte-identical output, then cut
target.zip.

    python3 task250/generator/make.py            (full: two builds, the zip)
    python3 task250/generator/make.py --once     (one build, no zip)
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B
import golden as GD
import writeup as WU

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
STAMP = (2028, 1, 5, 7, 52, 0)        # the morning the folder was put together for the configuration


def metadata(target):
    files = []
    for k in B.PACK:
        f = B.FILES[k]
        p = os.path.join(target, f)
        if f.endswith(".csv"):
            rows = sum(1 for _ in open(p, encoding="utf-8")) - 1
        elif f.endswith(".parquet"):
            import pyarrow.parquet as pq
            rows = pq.ParquetFile(p).metadata.num_rows
        else:
            rows = None
        files.append({"path": f, "format": f.rsplit(".", 1)[1], "bytes": os.path.getsize(p), "rows": rows,
                      "source": "Constructed (seeded generator)", "date": "2028-01-05",
                      "license": "CC0-1.0 (original work)"})
    big = max((x for x in files if x["rows"]), key=lambda x: x["rows"])
    meta = {
        "task": "task250",
        "title": "Which drift-alert setting an irrigation consortium's agro-climatic station network should run in 2028 so "
                 "that drift alerts fit the field plan's visits, and how many a year it will raise, beside each "
                 "district's 2027 drift-alert visits, the days their alerts waited and its breakdown visits at the "
                 "stations kept",
        "domain": "Physical & Environmental Sciences",
        "subdomain": "sensor-calibration-measurement (the daily spatial-consistency check of a station network's air "
                     "temperature: inverse-distance estimates from the nearest reporting stations, a 14-day drift "
                     "statistic, limits from its recorded spread)",
        "objective": "Data Quality Monitoring & Alerting",
        "prompt_shape": "04: one dial (four settings), each setting's alerts a year, the setting and its count, beside "
                        "per-district audit figures of the field visits and a chart of the settings against the budget",
        "as_of": "2028-01-05",
        "deliverables": [GD.XLSX, GD.PNG],
        "distractor_files": [B.FILES[k] for k in B.DISTRACTORS],
        "context_artifacts": [B.FILES[k] for k in B.CONTEXT],
        "stated_inputs": ["the %d drift-alert visits of the field plan" % B.P.BUDGET_YEAR],
        "field_terms": [],
        "input_gates": {"files": len(files), "formats": sorted({x["format"] for x in files}),
                        "largest_file": big["path"], "largest_file_rows": big["rows"]},
        "sources": [{"files": "all files under target/",
                     "origin": "generated by task250/generator/make.py (seeded, deterministic) around a fictional "
                               "consortium of irrigation communities in Aragon running 148 agro-climatic stations: a "
                               "daily air-temperature field with a mesoscale part that decorrelates over tens of "
                               "kilometres and winter inversions, station noise, sensor drifts each set right at the "
                               "visit its alert sent or at the spring calibration round, the quality control's "
                               "inverse-distance estimates and 14-day drift statistic, the alerts at setting 3.0, two "
                               "maintenance contractors' work orders, the calibration database's transfer-standard "
                               "readings, the register with its sensor history, the documents and the request; the "
                               "consortium, the stations, "
                               "the contractors and every person are invented, the quality-control method follows "
                               "published spatial-consistency practice for surface station networks, and no real "
                               "dataset is reproduced.",
                     "date": "2028-01-05", "license": "CC0-1.0 (original work)"}],
        "created": "2026-10-20",
        "generator": "task250/generator/make.py",
        "files": files,
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def stamp(folder):
    t = dt.datetime(*STAMP, tzinfo=dt.timezone.utc).timestamp()
    for f in os.listdir(folder):
        os.utime(os.path.join(folder, f), (t, t))


def digest(folder):
    return {f: hashlib.sha256(open(os.path.join(folder, f), "rb").read()).hexdigest() for f in sorted(os.listdir(folder))}


def cut_zip():
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(os.listdir(TARGET)):
            zi = zipfile.ZipInfo(f, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TARGET, f), "rb").read())
    return zp


def fresh(folder):
    if os.path.isdir(folder):
        for f in os.listdir(folder):
            os.remove(os.path.join(folder, f))
    os.makedirs(folder, exist_ok=True)


def goldens(target, golden):
    fig = WU.figures(target, B.FILES)
    GD.write(golden, WU.golden_content(fig))
    return fig


def main(second=True, checks=True):
    fresh(TARGET)
    world = B.run(TARGET)
    stamp(TARGET)
    fresh(GOLDEN)
    fig = goldens(TARGET, GOLDEN)
    stamp(GOLDEN)
    WU.write_figures(os.path.join(HERE, "figures.json"), fig)
    with open(os.path.join(TASK, "submission.md"), "w") as fh:
        fh.write(WU.submission(fig))
    metadata(TARGET)
    if checks:
        import checks as C
        n = C.run(TARGET, world, fig, GOLDEN)
        print("checks: %d passed" % n)
        import verify as V
        fails = V.main(TARGET)
        assert not fails, fails
    if second:
        tmp = tempfile.mkdtemp(dir=os.environ.get("TMPBUILD"))
        t2, g2 = os.path.join(tmp, "target"), os.path.join(tmp, "golden")
        B.run(t2)
        stamp(t2)
        os.makedirs(g2, exist_ok=True)
        goldens(t2, g2)
        stamp(g2)
        d1, d2 = digest(TARGET), digest(t2)
        assert d1 == d2, [f for f in d1 if d1[f] != d2.get(f)]
        assert digest(GOLDEN) == digest(g2), "golden differs between builds"
        shutil.rmtree(tmp)
        zp = cut_zip()
        print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
    return fig


if __name__ == "__main__":
    main(second="--once" not in sys.argv, checks="--nochecks" not in sys.argv)
