"""Build the pack, compute every owed figure from it, write the goldens, figures.json, submission.md and metadata.json,
run the checks and the independent verifier, rebuild into a scratch folder and require byte-identical output, then cut
target.zip.

    python3 task250/generator/make.py            (full: two builds, the zip)
    python3 task250/generator/make.py --once     (one build, no zip)
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B
import golden as GD
import postprocess
import writeup as WU

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
STAMP = (2026, 11, 6, 8, 5, 0)        # the morning the extract and the documents were put in the folder


def metadata(target):
    import pyarrow.parquet as pq
    files = []
    for k in B.PACK:
        f = B.FILES[k]
        p = os.path.join(target, f)
        if f.endswith(".csv"):
            rows = sum(1 for _ in open(p, encoding="utf-8")) - 1
        elif f.endswith(".parquet"):
            rows = pq.ParquetFile(p).metadata.num_rows
        else:
            rows = None
        files.append({"path": f, "format": f.rsplit(".", 1)[1], "bytes": os.path.getsize(p), "rows": rows,
                      "source": "Constructed (seeded generator)", "date": "2026-11-06",
                      "license": "CC0-1.0 (original work)"})
    big = max((x for x in files if x["rows"]), key=lambda x: x["rows"])
    meta = {
        "task": "task250",
        "title": "Whether the tracking data standard's scan alert fires at any of a regional parcel carrier's sort hubs "
                 "for October 2026, and at which, beside each depot's courier events sent twice and its pre-advised "
                 "parcels never picked up",
        "domain": "General Statistics & Data Science",
        "subdomain": "missing-data-censoring-measurement-error (whether the tracking standard's scan alert fires at a "
                     "carrier's sort hubs for a closed month)",
        "objective": "Data Quality Monitoring & Alerting",
        "prompt_shape": "10: a scorecard of every sort hub against one tolerance (parcels handled, missed sort scans, "
                        "rate and alert per hub), beside per-depot counts of courier events sent twice and of "
                        "pre-advised parcels never picked up, and a chart of the hubs' rates against the tolerance",
        "as_of": "2026-11-06",
        "deliverables": [GD.XLSX, GD.PPTX],
        "distractor_files": [B.FILES[k] for k in B.DISTRACTORS],
        "context_artifacts": [B.FILES[k] for k in B.CONTEXT],
        "stated_inputs": [],
        "field_terms": [],
        "input_gates": {"files": len(files), "formats": sorted({x["format"] for x in files}),
                        "largest_file": big["path"], "largest_file_rows": big["rows"]},
        "sources": [{"files": "all files under target/",
                     "origin": "generated by task250/generator/make.py (seeded, deterministic) around a fictional "
                               "regional parcel carrier in Poland with six sort hubs and twelve delivery depots: a month "
                               "of parcels collected, sorted and delivered, the platform's sort, arrival and courier "
                               "events as each source writes them, the shippers' pre-advices and accounts, the sort "
                               "plan, the network register, the tracking data standard, a request and two operational "
                               "files; the carrier, its sites' operations and every person are invented, the town and "
                               "street names are real places used for realism, and no real dataset is reproduced.",
                     "date": "2026-11-06", "license": "CC0-1.0 (original work)"}],
        "created": "2026-10-31",
        "generator": "task250/generator/make.py",
        "files": files,
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def stamp(folder):
    t = dt.datetime(*STAMP, tzinfo=dt.timezone.utc).timestamp()
    for f in os.listdir(folder):
        os.utime(os.path.join(folder, f), (t, t))


def digest(folder):
    return {f: hashlib.sha256(open(os.path.join(folder, f), "rb").read()).hexdigest() for f in sorted(os.listdir(folder))}


def cut_zip():
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(os.listdir(TARGET)):
            zi = zipfile.ZipInfo(f, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TARGET, f), "rb").read())
    return zp


def fresh(folder):
    if os.path.isdir(folder):
        for f in os.listdir(folder):
            os.remove(os.path.join(folder, f))
    os.makedirs(folder, exist_ok=True)


def goldens(target, golden):
    fig = GD.figures(target, B.FILES)
    GD.write(golden, fig)
    for name, (created, modified) in ((GD.XLSX, ("2026-11-06T08:58:00Z", "2026-11-06T13:41:00Z")),
                                      (GD.PPTX, ("2026-11-06T13:02:00Z", "2026-11-06T14:16:00Z"))):
        x = os.path.join(golden, name)
        postprocess.scrub(x, "Kurier Warta sp. z o.o.", "2026-11-06")
        postprocess.finish_office(x, created, modified, "Kurier Warta sp. z o.o.")
    return fig


def main(second=True, checks=True):
    fresh(TARGET)
    world = B.run(TARGET)
    stamp(TARGET)
    fresh(GOLDEN)
    fig = goldens(TARGET, GOLDEN)
    stamp(GOLDEN)
    ex = WU.extras(TARGET, B.FILES)
    WU.write_figures(os.path.join(HERE, "figures.json"), fig, ex)
    with open(os.path.join(TASK, "submission.md"), "w") as fh:
        fh.write(WU.submission(fig, ex))
    metadata(TARGET)
    if checks:
        import checks as C
        n = C.run(TARGET, world, fig, GOLDEN)
        print("checks: %d passed" % n)
        import verify as V
        fails = V.main(TARGET)
        assert not fails, fails
        print("verify: PASS")
    if second:
        tmp = tempfile.mkdtemp(dir=os.environ.get("TMPBUILD"))
        t2, g2 = os.path.join(tmp, "target"), os.path.join(tmp, "golden")
        B.run(t2)
        stamp(t2)
        os.makedirs(g2, exist_ok=True)
        goldens(t2, g2)
        stamp(g2)
        d1, d2 = digest(TARGET), digest(t2)
        assert d1 == d2, [f for f in d1 if d1[f] != d2.get(f)]
        assert digest(GOLDEN) == digest(g2), "golden differs between builds"
        shutil.rmtree(tmp)
        zp = cut_zip()
        print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
    return fig


if __name__ == "__main__":
    main(second="--once" not in sys.argv, checks="--nochecks" not in sys.argv)
