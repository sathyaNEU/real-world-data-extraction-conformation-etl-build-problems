"""Build the pack, compute every owed figure from it, write the goldens, figures.json, submission.md and metadata.json,
rebuild into a scratch folder and require byte-identical output, cut target.zip, then run the checks and the
independent verifier on the cut.

    python3 task468/generator/make.py
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import figs as F       # noqa: E402
import golden as GD    # noqa: E402
import pack as K       # noqa: E402
import writeup as WU   # noqa: E402

TASK = os.path.dirname(HERE)
STAMP = (2027, 2, 3, 9, 0, 0)

SOURCES = {
    "pp_hist": "a land registry's open price paid record for one city, transfers dated 2015 to 2025, in its header-less layout",
    "pp_2026": "the same record's yearly file for transfers dated 2026",
    "pp_update": "the record's January 2027 monthly update (additions, changes and deletions)",
    "postcodes": "a postcode directory for the city with its 2019 and May 2023 ward codes",
    "wards": "the ward codes and names before and after the May 2023 boundary review",
    "register": "a city council's building control completions export from two systems",
    "method": "a regional housing agency's ward house price index methodology",
    "rules": "the agency's programme rules for a grant uplift in pressured wards",
    "pipeline": "the agency's affordable homes pipeline for the programme year",
    "claims": "housing providers' start-on-site grant claims to the agency",
    "request": "the agency's Director of Investment asking for the committee paper",
    "official": "the official local authority house price index for the city (a mix-adjusted series)",
    "rents": "a private rents survey's ward medians by bedrooms",
}


def metadata():
    meta = {"task": "task468", "architecture": 5,
            "files": {K.FILES[k]: {"role": "distractor" if k in K.DISTRACTORS else "evidence",
                                   "source": "synthetic, generated by task468/generator (seeded)",
                                   "describes": SOURCES[k], "date": "2027-02-03", "license": "CC0-1.0"}
                      for k in K.FILES},
            "distractors": [K.FILES[k] for k in K.DISTRACTORS],
            "distractor_reasons": {
                K.FILES["official"]: "the official city-wide index is relevant to house price pressure but has no ward detail, so no ward's change can be read from it",
                K.FILES["rents"]: "rents bear on housing pressure but the programme rules test house prices only"},
            "stated_inputs": ["12,000,000", "12 million", "5.0"],
            "deliverables": [GD.PDF, GD.XLSX]}
    with open(os.path.join(TASK, "metadata.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=1, ensure_ascii=False)
        f.write("\n")


def build(root):
    target = os.path.join(root, "target")
    golden = os.path.join(root, "golden")
    for d in (target, golden):
        if os.path.exists(d):
            shutil.rmtree(d)
    K.build(target)
    fig = F.compute(target)
    with open(os.path.join(root, "figures.json"), "w", encoding="utf-8") as f:
        json.dump(fig, f, indent=1, sort_keys=True)
        f.write("\n")
    GD.write_all(target, golden, fig)
    WU.write(os.path.join(root, "submission.md"), fig)
    return fig


def digest(root):
    out = {}
    for sub in ("target", "golden"):
        for fn in sorted(os.listdir(os.path.join(root, sub))):
            out[sub + "/" + fn] = hashlib.sha256(open(os.path.join(root, sub, fn), "rb").read()).hexdigest()
    for fn in ("figures.json", "submission.md"):
        p = os.path.join(root, fn) if os.path.exists(os.path.join(root, fn)) else os.path.join(HERE, fn)
        out[fn] = hashlib.sha256(open(p, "rb").read()).hexdigest()
    return out


def main():
    fig = build(TASK)
    shutil.move(os.path.join(TASK, "figures.json"), os.path.join(HERE, "figures.json"))
    metadata()
    with tempfile.TemporaryDirectory() as tmp:
        build(tmp)
        a = digest(TASK)
        a["figures.json"] = hashlib.sha256(open(os.path.join(HERE, "figures.json"), "rb").read()).hexdigest()
        b = digest(tmp)
        diff = [k for k in a if a[k] != b.get(k)]
        if diff:
            print("NOT byte-identical:", diff)
            return 1
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for fn in sorted(K.FILES.values()):
            zi = zipfile.ZipInfo(fn, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TASK, "target", fn), "rb").read())
    print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
    print("call", fig["call"]["pressured"], fig["call"]["shares"])
    print("default", fig["default"]["pressured"])
    rc = 0
    for script in ("checks.py", "verify.py"):
        if os.path.exists(os.path.join(HERE, script)):
            rc |= subprocess.call([sys.executable, os.path.join(HERE, script)])
    return rc


if __name__ == "__main__":
    sys.exit(main())
