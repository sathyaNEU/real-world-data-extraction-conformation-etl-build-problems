"""Build the pack, compute every owed figure from it, write the goldens, figures.json, submission.md and metadata.json,
run the checks, rebuild into a scratch folder and require byte-identical output, cut target.zip and run the independent
verifier on it.

    python3 task301/generator/make.py            (full: two builds, the zip, the verifier)
    python3 task301/generator/make.py --once     (one build, no zip)
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B
import figs as FG
import golden as GD
import params as P
import writeup as WU

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
STAMP = (2026, 10, 21, 15, 40, 0)        # the afternoon the folder for the November executive meeting was put together


def metadata(target):
    files = []
    for k in B.PACK:
        f = B.FILES[k]
        p = os.path.join(target, f)
        rows = (sum(1 for _ in open(p, encoding="utf-8")) - 1) if f.endswith(".csv") else None
        if f.endswith(".parquet"):
            import pyarrow.parquet as pq
            rows = pq.ParquetFile(p).metadata.num_rows
        files.append({"path": f, "format": f.rsplit(".", 1)[1], "bytes": os.path.getsize(p), "rows": rows,
                      "source": "Constructed (seeded generator)", "date": P.AS_OF.isoformat(),
                      "license": "CC0-1.0 (original work)"})
    big = max((x for x in files if x["rows"]), key=lambda x: x["rows"])
    meta = {
        "task": "task301",
        "title": "Which of four sub-regions a primary health network's quit outreach team works in during 2027, by the "
                 "patients it helps to quit there, with three measures of existing referrals and the 2025 team's work",
        "domain": "Epidemiology & Public Health",
        "subdomain": "health-burden-impact-modeling (the quits a cessation programme achieves in each candidate "
                     "population, from the smokers still smoking when it acts and its own conversion)",
        "objective": "Opportunity Sizing & Decision Support",
        "prompt_shape": "other: one of four sub-regions and its 2027 quits, with a chart of the four, and three asks "
                        "on the Quitline report and the 2025 team's dialler export",
        "as_of": P.AS_OF.isoformat(),
        "deliverables": [GD.DOCX, GD.XLSX],
        "distractor_files": [B.FILES[k] for k in B.DISTRACTORS],
        "context_artifacts": [B.FILES[k] for k in B.CONTEXT],
        "stated_inputs": ["the 2027 placement: the team calls every active patient the sub-region's practices record "
                          "as a current smoker in the 30 September 2026 extract, once each, spread evenly through 2027, "
                          "working as in Eastern Shore in 2025 (placement paper)",
                          "a quit is a patient the team calls who sets a quit date and is not smoking four weeks after "
                          "it, lost to follow-up counted as smoking (placement paper)",
                          "a current smoker is a daily, weekly or irregular smoker or a smoker (data dictionary)"],
        "field_terms": [],
        "input_gates": {"files": len(files), "formats": sorted({x["format"] for x in files}),
                        "largest_file": big["path"], "largest_file_rows": big["rows"]},
        "sources": [{"files": "all files under target/",
                     "origin": "generated by task301/generator/make.py (seeded, deterministic) around a fictional "
                               "primary health network in New South Wales with five sub-regions and 61 general "
                               "practices: each active adult patient's true smoking history as a two-state process at "
                               "the sub-region's own rates of stopping and relapse, the statuses the practices recorded "
                               "at consultations from 2012 under two clinical systems' vocabularies, Eastern Shore's "
                               "2024 recording drive, the quit outreach team's 2025 list, calls and four-week outcomes, "
                               "the state Quitline's monthly referral report and the team's dialler export; every "
                               "organisation, practice and person is invented, and no real dataset is reproduced.",
                     "date": P.AS_OF.isoformat(), "license": "CC0-1.0 (original work)"}],
        "created": "2026-10-25",
        "generator": "task301/generator/make.py",
        "files": files,
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def stamp(folder):
    t = dt.datetime(*STAMP, tzinfo=dt.timezone.utc).timestamp()
    for f in os.listdir(folder):
        os.utime(os.path.join(folder, f), (t, t))


def digest(folder):
    return {f: hashlib.sha256(open(os.path.join(folder, f), "rb").read()).hexdigest() for f in sorted(os.listdir(folder))}


def cut_zip():
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(os.listdir(TARGET)):
            zi = zipfile.ZipInfo(f, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TARGET, f), "rb").read())
    return zp


def fresh(folder):
    if os.path.isdir(folder):
        for f in os.listdir(folder):
            os.remove(os.path.join(folder, f))
    os.makedirs(folder, exist_ok=True)


def main(second=True, checks=True):
    fresh(TARGET)
    R = B.build(TARGET)
    stamp(TARGET)
    fresh(GOLDEN)
    F, X = FG.compute(TARGET)
    F = json.loads(json.dumps(F))
    with open(os.path.join(HERE, "figures.json"), "w") as fh:
        json.dump(F, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    GD.write(GOLDEN, F, X)
    stamp(GOLDEN)
    WU.write(os.path.join(TASK, "submission.md"), F)
    metadata(TARGET)
    if checks:
        import checks as C
        assert not C.main(TARGET, R)
    if second:
        tmp = tempfile.mkdtemp()
        t2, g2 = os.path.join(tmp, "target"), os.path.join(tmp, "golden")
        B.build(t2)
        stamp(t2)
        F2, X2 = FG.compute(t2)
        F2 = json.loads(json.dumps(F2))
        GD.write(g2, F2, X2)
        stamp(g2)
        d1, d2 = digest(TARGET), digest(t2)
        assert d1 == d2, [f for f in d1 if d1[f] != d2.get(f)]
        assert digest(GOLDEN) == digest(g2), [f for f in digest(GOLDEN) if digest(GOLDEN)[f] != digest(g2).get(f)]
        assert F == F2
        shutil.rmtree(tmp)
        zp = cut_zip()
        print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
        import verify as V
        assert not V.main(zp)
    return F


if __name__ == "__main__":
    main(second="--once" not in sys.argv, checks="--nochecks" not in sys.argv)
