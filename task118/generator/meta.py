"""metadata.json beside target/: the decision, the deliverables, the distractors and each file's provenance."""
import json
import os

import pack as K
import golden as GD

TASK = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = {
    "running": "a train operator's weekday train running extract (calls at timing points with unit numbers)",
    "wtt": "a working timetable with its planning rules",
    "census": "an operator's annual passenger count by train and station",
    "stations": "a network station register",
    "brief": "a transport authority's siting brief",
    "perf": "a concession's monthly weekday performance summary",
    "gates": "a ticket gateline system's quarter-hourly counter readings",
    "repay": "an operator's Delay Repay claims extract",
    "incidents": "an operator's delay incident log",
    "usage": "annual station entries and exits estimates",
}


def write(target, fig):
    files = []
    for k, f in K.FILES.items():
        p = os.path.join(target, f)
        rows = None
        if f.endswith(".csv"):
            rows = sum(1 for _ in open(p, encoding="utf-8")) - 1
        files.append({"path": f, "format": f.rsplit(".", 1)[1], "bytes": os.path.getsize(p), "rows": rows,
                      "source": "Constructed (seeded generator) in the layout of %s" % SOURCES[k],
                      "date": "2027-01-18", "license": "CC0-1.0 (original work)"})
    big = max((x for x in files if x["rows"]), key=lambda x: x["rows"])
    meta = {
        "task": "task118",
        "title": "Where Ravelstoke Rail's 2027 platform dispatch team should go, with a census-day gateline count and "
                 "the autumn 2026 Delay Repay compensation",
        "domain": "Urban & Regional Science",
        "subdomain": "optimization",
        "objective": "Opportunity Sizing & Decision Support",
        "decision": "one shortlisted station receives the platform dispatch team the 2027 Rail Plan funds",
        "as_of": "2027-01-18",
        "deliverables": [GD.XLSX, GD.PNG],
        "distractor_files": [K.FILES[k] for k in K.DISTRACTORS],
        "input_gates": {"files": len(files), "formats": sorted({x["format"] for x in files}),
                        "largest_file": big["path"], "largest_file_rows": big["rows"]},
        "sources": [{"files": "all files under target/",
                     "origin": "generated by task118/generator/make.py (seeded, deterministic) around a fictional "
                               "English city region's suburban rail network; layouts follow the kinds of operator and "
                               "authority files named per file; every organisation, place and person is invented, and "
                               "no real dataset is reproduced.",
                     "date": "2027-01-18", "license": "CC0-1.0 (original work)"}],
        "created": "2026-11-07",
        "generator": "task118/generator/make.py",
        "files": files,
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
