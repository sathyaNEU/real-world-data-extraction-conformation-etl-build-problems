#!/usr/bin/env python3
"""Build task196's bundle from a fixed seed.

    python3 task196/generator/build.py

Writes target/, golden/, metadata.json and generator/figures.json, then normalises every mtime inside
target/ to the pack's own export date so two consecutive runs give identical bytes.
"""
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
TASK = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import askpack
import docs
import golden
import pack
import world as W

TARGET = os.path.join(TASK, "target")


def metadata(w, figures):
    cg = figures["call"]
    data = {
        "task": "task196",
        "domain": "Banking, Credit & Financial Risk, fraud and AML detection",
        "objective": "Anomaly Detection & Diagnostics",
        "as_of": W.AS_OF.isoformat(),
        "committed_answer": (
            "set Castlegate Payments' scam incidence index for the indemnity year beginning 1 October "
            "2027 at %d scam cases per million payments sent, being %d indexed cases on %d payments, "
            "against the %d cases its own register holds"
            % (cg["index_per_million"], cg["indexed_cases"], cg["payments_sent"], cg["recorded_cases"])),
        "deliverables": figures["deliverables"],
        "distractor_files": [
            {"file": "national_scam_statistics_calendar_year.csv",
             "why_relevant": "a published national scam series is the first benchmark anyone reaches for "
                             "when asked whether a member's incidence is out of line",
             "why_unused": "it is published per million pounds of payment value on calendar quarters, "
                           "the pack carries no value-to-count conversion, and no graded figure uses it"},
            {"file": "aml_alert_summary.csv",
             "why_relevant": "alert volumes and escalation rates read as a direct measure of how much "
                             "fraud a member's own monitoring is catching",
             "why_unused": "alerts are not cases, the summary is at member-quarter grain with no case "
                           "key, and no graded figure uses it"},
            {"file": "case_register_2023_24.csv",
             "why_relevant": "the earliest year of the same register, in the layout the mutual used "
                             "before 2024/25, and the obvious place to look for a baseline",
             "why_unused": "the index is measured over the scheme year ended 31 March 2027 and no "
                           "graded figure reads the 2023/24 extract"}
        ],
        "stated_inputs": [
            W.AS_OF.isoformat(), "2027-10-01", "2027-06-30", "2026-04-01",
            str(cg["payments_sent"]), "1,000,000", "2026/27", "2025/26"
        ],
        "declared_wrong_basis_distractor": None,
        "sources": [
            {"file": "all files under target/",
             "origin": "synthetic, generated by task196/generator from a fixed seed",
             "date": W.PULL.isoformat(),
             "license": "generated for this task; no third party data is included"}
        ]
    }
    with open(os.path.join(TASK, "metadata.json"), "w", encoding="utf-8") as f:
        json.dump(data, f, indent=1)
    return data


def normalise_mtimes():
    stamp = time.mktime(W.PULL.timetuple()) + 9 * 3600
    for root, _dirs, files in os.walk(TARGET):
        for name in sorted(files):
            os.utime(os.path.join(root, name), (stamp, stamp))


def main():
    os.makedirs(TARGET, exist_ok=True)
    for name in os.listdir(TARGET):
        os.remove(os.path.join(TARGET, name))
    w = W.world()
    counts = pack.write_all(TARGET, w)
    counts["advices"] = askpack.settlement_advices(TARGET, w)
    counts["recovery"] = askpack.recovery_statements(TARGET, w)
    main_rows, supp_rows, mn, sp = askpack.q1_notifications(TARGET, w)
    counts["q1"] = (main_rows, supp_rows)
    askpack.q1_return_sheet(TARGET, w, mn, sp)
    askpack.reference_files(TARGET, w)
    docs.write_all(TARGET, w)
    counts["manifest"] = askpack.manifest(TARGET, w, counts)
    figures, review, bridge = golden.build(TASK, TARGET, w)
    metadata(w, figures)
    normalise_mtimes()
    files = sorted(os.listdir(TARGET))
    print("target/: %d files" % len(files))
    for n in files:
        print("   %9d  %s" % (os.path.getsize(os.path.join(TARGET, n)), n))
    print()
    print("call: %s" % figures["call"]["sentence"])
    print("ladder: %s" % json.dumps(figures["ladder"]))
    print("review group: %s" % json.dumps(figures["review_group_index"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
