def submission_answers(sub):
    """Numbers and names from block 1 and block 4 of a five-block submission.md."""
    b1 = re.search(r"## 1\..*?(?=\n## 2\.)", sub, re.S)
    b4 = re.search(r"## 4\..*", sub, re.S)
    b1 = b1.group(0) if b1 else ""
    b4 = b4.group(0) if b4 else ""
    nums = set()
    for blk in (b1, b4):
        for n in NUM.findall(blk):
            s = n.replace(",", "").lstrip("+")
            try:
                v = float(s)
            except ValueError:
                continue
            if 1900 <= v <= 2100 and "." not in s:  # a year
                continue
            if abs(v) < 10 and "." not in s:
                continue
            nums.add(n.lstrip("+"))
    call = re.search(r"\*\*(.+?)\*\*", b1)
    call = call.group(1) if call else ""
    names = set()
    for blk in (b1, b4):
        for m in re.finditer(r"\b([A-Z][a-z]+(?:[ '][A-Z][a-zA-Z']+){1,4})\b", blk):
            if m.group(1).split()[0] not in ("The", "Not", "We", "Each", "Per", "For", "Deliverable", "Final", "Critical", "Step"):
                names.add(m.group(1))
    return nums, names, call, b4


def design_vocab(note, prompt_text):
    """Distinctive terms from the design note's stump and driver paragraphs that the prompt does not use."""
    if not note:
        return []
    paras = []
    for p in re.split(r"\n\s*\n", note):
        if re.search(r"\b(stump|driver|decisive|rung 0|the wrong committed|lands them)\b", p, re.I):
            paras.append(p)
    text = "\n".join(paras[:12])
    words = [w for w in re.findall(r"[a-z][a-z\-]{5,}", text.lower()) if w not in STOP]
    pw = set(re.findall(r"[a-z][a-z\-]{5,}", prompt_text.lower()))
    cnt = Counter(w for w in words if w not in pw)
    return [w for w, c in cnt.most_common(40) if c >= 2 and not w.startswith(("solver", "respons", "portal", "rubric"))][:25]


# ------------------------------------------------------------------ sweeps

class Report:
    def __init__(self):
        self.items = defaultdict(list)  # sweep -> [(level, file, detail)]

    def add(self, sweep, level, file, detail):
        self.items[sweep].append((level, str(file), detail))

    def level(self):
        levels = [lv for v in self.items.values() for lv, _, _ in v]
        if "LEAK" in levels:
            return "LEAK"
        if "REVIEW" in levels:
            return "REVIEW"
        return "CLEAN"


def ctx(text, m, w=70):
    a, b = max(0, m.start() - w), min(len(text), m.end() + w)
    return re.sub(r"\s+", " ", text[a:b]).strip()


def sweep_names(files, rep):
    for f in files:
        rel = f["rel"]
        if BAD_NAME.search(rel.name) or BAD_NAME.search(str(rel.parent)):
            rep.add("1 file names", "LEAK", rel, "name matches the author's vocabulary: %s" % BAD_NAME.search(rel.name or str(rel)).group(0))
        if rel.name.startswith(".") or rel.name in ("Thumbs.db", "desktop.ini") or "__MACOSX" in str(rel):
            rep.add("1 file names", "LEAK", rel, "stray system or dot file")
        if f["ext"] in (".py", ".ipynb", ".r", ".sql", ".sh"):
            rep.add("1 file names", "REVIEW", rel, "code shipped in the input pack, confirm it is in-fiction and carries no construction of the answer")


TOOLCHAIN = re.compile(r"python-docx|openpyxl|reportlab|matplotlib|pandas|numpy|faker|pyarrow|seed\s*=|scratchpad|/Users/|claude|anthropic|lorem|placeholder|TODO|FIXME|as an ai", re.I)


def sweep_vocab(files, rep):
    for f in files:
        t = f["text"]
        if not t:
            continue
        isdata = f["ext"] in DATA_EXT
        for pat, lv in AUTHOR_VOCAB:
            # A data file carries real-world strings (GOLDEN is an Irish electoral division), so only
            # the toolchain patterns are swept there; the author's nouns are swept in documents.
            if isdata and not TOOLCHAIN.search(pat.replace("\\b", "")):
                continue
            ms = list(re.finditer(pat, t, re.I))
            if not ms:
                continue
            if pat == "\u2014":
                rep.add("2 author vocabulary", "REVIEW", f["rel"], "%d em dash(es)" % len(ms))
                continue
            rep.add("2 author vocabulary", lv, f["rel"], "%s x%d: ...%s..." % (pat, len(ms), ctx(t, ms[0])))


def sweep_answers(files, rep, nums, names, call, prompt_text):
    given = set(n for n in NUM.findall(prompt_text))
    for f in files:
        t = f["text"]
        if not t:
            continue
        isdoc = f["ext"] in DOC_EXT
        hits = []
        for n in sorted(nums, key=len, reverse=True):
            if n in given:
                continue
            digits = len(re.sub(r"\D", "", n))
            if not isdoc and digits < 5:
                continue  # a short figure recurs in any data file by chance
            m = re.search(r"(?<![\d.])" + re.escape(n) + r"(?![\d])", t)
            if m:
                hits.append((n, ctx(t, m, 50), digits))
        if hits:
            for n, c, digits in hits[:12]:
                lv = "LEAK" if (isdoc and digits >= 4) else "REVIEW"
                rep.add("3 answer figures in the pack", lv, f["rel"], "golden figure %s appears: ...%s..." % (n, c))
            if len(hits) > 12:
                rep.add("3 answer figures in the pack", lv, f["rel"], "and %d more golden figures" % (len(hits) - 12))
        if isdoc:
            for nm in names:
                for m in re.finditer(re.escape(nm), t):
                    window = t[max(0, m.start() - 120): m.end() + 120].lower()
                    if re.search(r"\b(recommend|select|winner|wins|best|top|highest|lowest|rank|first out|chosen|pick|prefer|should get|should take|goes to)\b", window):
                        rep.add("3 answer figures in the pack", "REVIEW", f["rel"], "candidate %r sits beside decision vocabulary: ...%s..." % (nm, ctx(t, m, 90)))
                        break
    if call:
        toks = [w for w in re.findall(r"[A-Za-z][A-Za-z']{3,}", call) if w.lower() not in STOP]
        for f in files:
            if f["ext"] in DOC_EXT and f["text"] and len(toks) >= 3:
                have = sum(1 for w in toks if re.search(r"\b" + re.escape(w) + r"\b", f["text"], re.I))
                if have >= max(3, int(0.7 * len(toks))):
                    rep.add("3 answer figures in the pack", "REVIEW", f["rel"], "carries %d of %d distinctive words of the committed call: %r" % (have, len(toks), call[:120]))


def sweep_design_vocab(files, rep, vocab, prompt_text):
    if not vocab:
        rep.add("4 design-note vocabulary", "INFO", "-", "no design note or no stump paragraph found, sweep skipped")
        return
    for f in files:
        if f["ext"] not in DOC_EXT or not f["text"]:
            continue
        found = []
        for w in vocab:
            m = re.search(r"\b" + re.escape(w) + r"\w*", f["text"], re.I)
            if m:
                found.append((w, ctx(f["text"], m, 45)))
        if len(found) >= 3:
            rep.add("4 design-note vocabulary", "REVIEW", f["rel"], "%d of %d stump-paragraph terms appear (%s); read whether the document names the move" % (len(found), len(vocab), ", ".join(w for w, _ in found[:6])))
    ps = [s for s in re.split(r"(?<=[.!?])\s+", prompt_text) if sum(1 for w in vocab if re.search(r"\b" + re.escape(w), s, re.I)) >= 2]
    for s in ps[:6]:
        rep.add("4 design-note vocabulary", "REVIEW", "prompt.md", "prompt sentence carries two or more stump terms: %r" % re.sub(r"\s+", " ", s)[:220])


def sweep_announce(files, rep, prompt_text):
    srcs = [("prompt.md", prompt_text)] + [(str(f["rel"]), f["text"]) for f in files if f["ext"] in DOC_EXT and f["text"]]
    for name, t in srcs:
        for s in re.split(r"(?<=[.!?])\s+", t):
            if len(s) > 400:
                continue
            for pat in ANNOUNCE:
                if re.search(pat, s, re.I):
                    rep.add("5 announcements", "REVIEW", name, re.sub(r"\s+", " ", s).strip()[:260])
                    break


def sweep_rank_artifact(files, rep, names):
    cands = [n for n in names if len(n) > 5]
    if len(cands) < 3:
        return
    for f in files:
        t = f["text"]
        if not t:
            continue
        have = [n for n in cands if n in t]
        if len(have) >= min(3, len(cands)):
            numeric = len(NUM.findall(t[:200000])) > 20
            lv = "REVIEW" if numeric else "INFO"
            rep.add("6 ranking artifacts", lv, f["rel"], "names %d of %d answer-set candidates%s; confirm it does not rank them on the decision question" % (len(have), len(cands), " beside numbers" if numeric else ""))


def sweep_hidden(files, rep):
    for f in files:
        x = f["extras"]
        for k in ("hidden_sheets", "hidden_rows_cols", "defined_names", "comments", "tracked_changes", "hidden_text", "annotations", "embedded", "embedded_files", "nested_zip"):
            if x.get(k):
                lv = "LEAK" if k in ("hidden_sheets", "hidden_text", "tracked_changes", "comments") else "REVIEW"
                rep.add("7 hidden content", lv, f["rel"], "%s: %s" % (k, json.dumps(x[k])[:200]))
        if x.get("error"):
            rep.add("7 hidden content", "REVIEW", f["rel"], "could not be read: %s" % x["error"][:120])


def sweep_columns(files, rep):
    pat = re.compile(r"(^|_)(true|truth|actual|hidden|trap|flag|is_|seed|synthetic|gen_|generated|golden|answer|correct|naive|rung|device|hazard|planted|debug|tmp|temp|internal)(_|$)", re.I)
    for f in files:
        cols = columns_of(f["rel"], f["text"]) if f["ext"] in DATA_EXT else []
        bad = [c for c in cols if c and pat.search(c)]
        if bad:
            rep.add("8 column names", "REVIEW", f["rel"], "columns a generator names and an organisation does not: %s" % ", ".join(bad[:8]))
        if f["ext"] in (".csv", ".tsv") and f["text"]:
            head = f["text"].split("\n")[:50]
            if any(re.search(r"\b(nan|NaN|None|NULL|True|False)\b", l) for l in head):
                rep.add("8 column names", "REVIEW", f["rel"], "Python-style nulls or booleans (nan/None/True/False) in the first rows")


def sweep_dates(files, rep, asof, prompt_text):
    if not asof:
        rep.add("9 dates after the setting", "INFO", "-", "no --asof given, sweep skipped (pass the fiction's as-of date)")
        return
    given = set(re.findall(r"\b(20\d\d)-(\d\d)-(\d\d)\b", prompt_text))
    for f in files:
        if not f["text"]:
            continue
        late = Counter()
        for m in re.finditer(r"\b(20\d\d)-(\d\d)-(\d\d)\b", f["text"]):
            d = "-".join(m.groups())
            if d > asof and m.groups() not in given:
                late[d] += 1
        if late:
            rep.add("9 dates after the setting", "REVIEW", f["rel"], "%d ISO dates after %s, e.g. %s" % (sum(late.values()), asof, ", ".join(sorted(late)[:5])))


def sweep_metadata(target, rep):
    if not SCRUB.exists():
        rep.add("10 container metadata", "INFO", "-", "scrub script not found")
        return
    r = subprocess.run([sys.executable, str(SCRUB), str(target)], capture_output=True, text=True)
    out = (r.stdout + r.stderr).strip()
    flagged = [l for l in out.split("\n")
               if re.search(r"python-docx|openpyxl|reportlab|matplotlib|pypdf|LibreOffice|Microsoft|outside the band|out-of-band timestamp", l, re.I)
               and not re.search(r"\bno (producer|writer|out-of-band)|clean\b", l, re.I)]
    if flagged:
        for l in flagged[:15]:
            rep.add("10 container metadata", "LEAK", "-", l.strip()[:200])
    else:
        rep.add("10 container metadata", "INFO", "-", "audit reported no writer signature (%d lines)" % len(out.split("\n")))


def sweep_prompt(prompt_text, rep):
    for pat, what in (
        (r"\[[^\]]{3,}\]", "bracketed block"),
        (r"\(\s*(CSV|XLSX|PDF|DOCX|PNG|PPTX|JSON|Parquet)\s*\)", "file.ext (Family) header"),
        (r"^\s*[-*]\s", "bulleted ask"),
        (r"\u2014", "em dash"),
    ):
        ms = list(re.finditer(pat, prompt_text, re.M))
        if ms:
            rep.add("11 prompt form", "REVIEW", "prompt.md", "%s x%d: %r" % (what, len(ms), ctx(prompt_text, ms[0], 40)))
    for pat in (r"\b(step \d|first,? (compute|calculate|join)|then (compute|calculate|join)|use the following method|the method is)\b",):
        for m in re.finditer(pat, prompt_text, re.I):
            rep.add("11 prompt form", "REVIEW", "prompt.md", "prompt enumerates method: ...%s..." % ctx(prompt_text, m, 60))


# ------------------------------------------------------------------ main

def load_target(task):
    tdir = task / "target"
    if tdir.is_dir():
        return tdir, None
    z = task / "target.zip"
    if not z.exists():
        sys.exit("no target/ and no target.zip in %s" % task)
    tmp = Path(tempfile.mkdtemp(prefix="leak-"))
    with zipfile.ZipFile(z) as zf:
        zf.extractall(tmp)
    inner = tmp / "target"
    return (inner if inner.is_dir() else tmp), tmp


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("task")
    ap.add_argument("--asof", help="the fiction's as-of date, ISO; dates after it are flagged")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args()
    task = Path(a.task)
    if not task.is_dir():
        t = a.task if a.task.startswith("task") else "task" + a.task
        task = REPO / t
    if not task.is_dir():
        sys.exit("no task folder: %s" % task)
    prompt_text = (task / "prompt.md").read_text(errors="ignore") if (task / "prompt.md").exists() else ""
    sub = (task / "submission.md").read_text(errors="ignore") if (task / "submission.md").exists() else ""
    note = (task / "DESIGN_NOTE.md").read_text(errors="ignore") if (task / "DESIGN_NOTE.md").exists() else ""
    target, tmp = load_target(task)

    files = []
    for p in sorted(target.rglob("*")):
        if p.is_file():
            text, extras = extract(p)
            files.append({"path": p, "rel": p.relative_to(target), "ext": p.suffix.lower(), "text": text, "extras": extras})

    rep = Report()
    nums, names, call, _ = submission_answers(sub)
    vocab = design_vocab(note, prompt_text)
    sweep_names(files, rep)
    sweep_vocab(files, rep)
    sweep_answers(files, rep, nums, names, call, prompt_text)
    sweep_design_vocab(files, rep, vocab, prompt_text)
    sweep_announce(files, rep, prompt_text)
    sweep_rank_artifact(files, rep, names)
    sweep_hidden(files, rep)
    sweep_columns(files, rep)
    sweep_dates(files, rep, a.asof, prompt_text)
    sweep_metadata(target, rep)
    sweep_prompt(prompt_text, rep)

    level = rep.level()
    lines = ["# leak check, %s" % task.name, "",
             "**Verdict: %s.** %d files read, %d golden figures and %d candidate names taken from submission.md, %d stump terms taken from the design note." % (level, len(files), len(nums), len(names), len(vocab)),
             "", "LEAK stops the ship. REVIEW is a reader's call and the /leak-check command's solver's-eye pass reads every REVIEW line. INFO is a sweep that ran and found nothing or was skipped.", ""]
    if vocab:
        lines += ["Stump terms swept: " + ", ".join(vocab), ""]
    order = sorted(rep.items.keys(), key=lambda k: int(k.split()[0]))
    for k in order:
        items = rep.items[k]
        counts = Counter(lv for lv, _, _ in items)
        lines.append("## %s (%s)" % (k, ", ".join("%s %d" % (lv, counts[lv]) for lv in ("LEAK", "REVIEW", "INFO") if counts[lv])))
        for lv, f, d in sorted(items, key=lambda x: ("LEAK", "REVIEW", "INFO").index(x[0])):
            lines.append("- **%s** `%s`: %s" % (lv, f, d))
        lines.append("")
    ran = set(order)
    for k in ("1 file names", "2 author vocabulary", "3 answer figures in the pack", "4 design-note vocabulary", "5 announcements", "6 ranking artifacts", "7 hidden content", "8 column names", "9 dates after the setting", "10 container metadata", "11 prompt form"):
        if k not in ran:
            lines.append("## %s (clean)\n" % k)
    out = task / "leak_check_report.md"
    out.write_text("\n".join(lines))
    if not a.quiet:
        print("\n".join(lines))
    print("\nverdict: %s  ->  %s" % (level, out))
    return {"LEAK": 2, "REVIEW": 1, "CLEAN": 0}[level]


