# ------------------------------------------------------------------ text extraction

def xml_text(data):
    return re.sub(r"<[^>]+>", " ", data.decode("utf-8", "ignore"))


def read_docx(path):
    out, extras = [], {}
    with zipfile.ZipFile(path) as z:
        names = z.namelist()
        for n in names:
            if n.startswith("word/") and n.endswith(".xml"):
                raw = z.read(n)
                out.append(xml_text(raw))
                if n == "word/document.xml":
                    if b"<w:del " in raw or b"<w:ins " in raw:
                        extras["tracked_changes"] = True
                    if b"<w:vanish" in raw:
                        extras["hidden_text"] = True
                if n == "word/comments.xml":
                    extras["comments"] = len(re.findall(rb"<w:comment ", raw))
            if n.startswith("docProps/"):
                extras.setdefault("docprops", []).append(xml_text(z.read(n)))
        media = [n for n in names if n.startswith("word/embeddings/") or n.startswith("word/media/")]
        if media:
            extras["embedded"] = media
    return "\n".join(out), extras


def read_xlsx(path):
    extras, out = {}, []
    try:
        import openpyxl
        wb = openpyxl.load_workbook(path, data_only=True, read_only=False)
    except Exception as e:
        return "", {"error": str(e)}
    hidden_sheets = [ws.title for ws in wb.worksheets if ws.sheet_state != "visible"]
    if hidden_sheets:
        extras["hidden_sheets"] = hidden_sheets
    try:
        dn = list(wb.defined_names.keys()) if hasattr(wb.defined_names, "keys") else [d.name for d in wb.defined_names.definedName]
        if dn:
            extras["defined_names"] = dn
    except Exception:
        pass
    for ws in wb.worksheets:
        hc = [k for k, d in ws.column_dimensions.items() if d.hidden]
        hr = [k for k, d in ws.row_dimensions.items() if d.hidden]
        if hc or hr:
            extras.setdefault("hidden_rows_cols", {})[ws.title] = {"cols": hc[:10], "rows": hr[:10]}
        comments = 0
        for row in ws.iter_rows():
            vals = []
            for c in row:
                if c.comment:
                    comments += 1
                if c.value is not None:
                    vals.append(str(c.value))
            if vals:
                out.append("\t".join(vals))
        if comments:
            extras.setdefault("comments", {})[ws.title] = comments
    with zipfile.ZipFile(path) as z:
        extras["docprops"] = [xml_text(z.read(n)) for n in z.namelist() if n.startswith("docProps/")]
    return "\n".join(out), extras


def read_pdf(path):
    extras, out = {}, []
    try:
        import pypdf
        r = pypdf.PdfReader(str(path))
        md = r.metadata or {}
        extras["metadata"] = {k: str(v) for k, v in md.items()}
        ann = 0
        for p in r.pages:
            out.append(p.extract_text() or "")
            if "/Annots" in p:
                ann += len(p["/Annots"])
        if ann:
            extras["annotations"] = ann
        if "/EmbeddedFiles" in str(r.trailer.get("/Root", {}).keys()):
            extras["embedded_files"] = True
    except Exception as e:
        extras["error"] = str(e)
    return "\n".join(out), extras


def read_parquet(path):
    try:
        import pandas as pd
        df = pd.read_parquet(path)
        return df.to_csv(index=False), {"columns": list(df.columns)}
    except Exception as e:
        return "", {"error": str(e)}


def read_png_text(path):
    raw = path.read_bytes()
    chunks = re.findall(rb"(tEXt|iTXt|zTXt)(.{0,200})", raw, re.S)
    return " ".join(c[1].decode("latin-1", "ignore") for c in chunks), {}


def extract(path):
    ext = path.suffix.lower()
    try:
        if ext == ".docx":
            return read_docx(path)
        if ext in (".xlsx", ".xlsm"):
            return read_xlsx(path)
        if ext == ".pdf":
            return read_pdf(path)
        if ext == ".parquet":
            return read_parquet(path)
        if ext in (".png", ".jpg", ".jpeg"):
            return read_png_text(path)
        if ext in (".zip",):
            return "", {"nested_zip": True}
        return path.read_text(encoding="utf-8", errors="ignore"), {}
    except Exception as e:
        return "", {"error": str(e)}


def columns_of(path, text):
    ext = path.suffix.lower()
    if ext in (".csv", ".tsv"):
        first = text.split("\n", 1)[0]
        return [c.strip().strip('"') for c in re.split(r"[,\t;|]", first)]
    if ext in (".xlsx",):
        return [c for line in text.split("\n")[:3] for c in line.split("\t")]
    if ext == ".json":
        return re.findall(r'"([A-Za-z_][A-Za-z0-9_ ]{1,40})"\s*:', text[:20000])
    return []


