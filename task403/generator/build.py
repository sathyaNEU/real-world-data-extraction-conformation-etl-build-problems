def calendar_xlsx(path, cal):
    from openpyxl import Workbook
    from openpyxl.styles import Font
    sheet = pack.calendar_sheet(cal)
    wb = Workbook()
    ws = wb.active
    ws.title = 'Release calendar'
    ws.append(list(sheet.columns))
    for c in ws[1]:
        c.font = Font(bold=True)
    for r in sheet.itertuples(index=False):
        ws.append(list(r))
    for col, w in zip('ABCDEFGHI', [20, 22, 7, 8, 17, 11, 38, 38, 38]):
        ws.column_dimensions[col].width = w
    wb.save(path)
    docs.xlsx_scrub(path, 'Content Planning', '2026-02-26T18:05:00Z', 'Release calendar')
    return sheet


