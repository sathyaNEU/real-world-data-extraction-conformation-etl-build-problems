def cut_zip():
    """target.zip from target/: the files at the root, sorted, one fixed date, deflated; byte-identical on rebuild."""
    import zipfile
    out = os.path.join(TASK, 'target.zip')
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:
        for fn in sorted(os.listdir(TGT)):
            zi = zipfile.ZipInfo(fn, date_time=(2026, 2, 27, 9, 30, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            with open(os.path.join(TGT, fn), 'rb') as f:
                z.writestr(zi, f.read())
    os.utime(out, (PACK_MTIME, PACK_MTIME))


