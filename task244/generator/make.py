"""Build the pack, compute every owed figure from it, write the goldens, figures.json, submission.md and metadata.json, run
the checks and the independent verifier, rebuild into a scratch folder and require byte-identical output, then cut
target.zip.

    python3 task244/generator/make.py            (full: two builds, the zip)
    python3 task244/generator/make.py --once     (one build, no zip)
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B
import golden as GD
import solve
import writeup as WU

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
STAMP = (2028, 2, 2, 8, 30, 0)        # the morning the release folder was put together for the quality note


def metadata(target):
    files = []
    for k in B.PACK:
        f = B.FILES[k]
        p = os.path.join(target, f)
        rows = sum(1 for _ in open(p, encoding="utf-8")) - 1 if f.endswith(".csv") else None
        files.append({"path": f, "format": f.rsplit(".", 1)[1], "bytes": os.path.getsize(p), "rows": rows,
                      "source": "Constructed (seeded generator)", "date": "2028-02-02",
                      "license": "CC0-1.0 (original work)"})
    big = max((x for x in files if x["rows"]), key=lambda x: x["rows"])
    meta = {
        "task": "task244",
        "title": "Whether a state statistics bureau's 2027 annual labour market flows go out without the "
                 "classification-error warning, and which of the 24 district job-finding and job-loss rates carry it, "
                 "with each district's match rate and reinterview timing",
        "domain": "Survey Research & Official Statistics",
        "subdomain": "nonresponse-calibration-measurement-error-adjustment (each published flow rate's share of counted "
                     "moves that are not real moves, the published flows read through the reconciled reinterview's "
                     "classification error at both quarters of each matched pair)",
        "objective": "Data Quality Monitoring & Alerting",
        "prompt_shape": "07: grid of cells, twelve survey districts by the job-finding and job-loss rates, each cell's "
                        "share of counted moves that are not real moves and its warning, with each district's match "
                        "rate, persons interviewed again and mean days from interview to reinterview, and a chart of "
                        "every rate against the warning line",
        "as_of": "2028-02-02",
        "deliverables": [GD.XLSX, GD.DOCX],
        "distractor_files": [B.FILES[k] for k in B.DISTRACTORS],
        "stated_inputs": [],
        "field_terms": [],
        "input_gates": {"files": len(files), "formats": sorted({x["format"] for x in files}),
                        "largest_file": big["path"], "largest_file_rows": big["rows"]},
        "sources": [{"files": "all files under target/",
                     "origin": "generated by task244/generator/make.py (seeded, deterministic) around a fictional state "
                               "bureau of statistics in south-west Nigeria: a quarterly labour force survey's rotating "
                               "panel of dwellings in twelve survey districts (each adult's labour force status quarter "
                               "to quarter, the status each interview records, households that split, move out or lose "
                               "members), the supervisors' reinterview with its fieldwork log and reconciled statuses, "
                               "the 2027 annual flows tables as tabulated, the district gazetteer after a boundary "
                               "change, population projections, the job centres' registers, the third-quarter bulletin, "
                               "the methodology note, the reinterview protocol and the request; the state, the bureau "
                               "and every person are invented, the labour force definitions and the reinterview practice "
                               "are real, and no real dataset is reproduced.",
                     "date": "2028-02-02", "license": "CC0-1.0 (original work)"}],
        "created": "2026-10-18",
        "generator": "task244/generator/make.py",
        "files": files,
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def stamp(folder):
    t = dt.datetime(*STAMP, tzinfo=dt.timezone.utc).timestamp()
    for f in os.listdir(folder):
        os.utime(os.path.join(folder, f), (t, t))


def digest(folder):
    return {f: hashlib.sha256(open(os.path.join(folder, f), "rb").read()).hexdigest() for f in sorted(os.listdir(folder))}


def cut_zip():
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(os.listdir(TARGET)):
            zi = zipfile.ZipInfo(f, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TARGET, f), "rb").read())
    return zp


def fresh(folder):
    if os.path.isdir(folder):
        for f in os.listdir(folder):
            os.remove(os.path.join(folder, f))
    os.makedirs(folder, exist_ok=True)


def goldens(target, golden):
    A = solve.answer(target, B.FILES)
    V, _ = solve.rungs(target, B.FILES, A)
    fig = WU.figures(A, V)
    GD.write(golden, fig, WU.golden_content(fig))
    return fig


def main(second=True, checks=True):
    fresh(TARGET)
    world = B.run(TARGET)
    stamp(TARGET)
    fresh(GOLDEN)
    fig = goldens(TARGET, GOLDEN)
    stamp(GOLDEN)
    WU.write(os.path.join(HERE, "figures.json"), fig)
    with open(os.path.join(TASK, "submission.md"), "w") as fh:
        fh.write(WU.submission(fig))
    metadata(TARGET)
    if checks:
        import checks as C
        n = C.run(TARGET, world["W"], world["R"], fig, GOLDEN)
        print("checks: %d passed" % n)
        import verify as V
        V.main(TARGET, GOLDEN, os.path.join(HERE, "figures.json"), os.path.join(TASK, "submission.md"))
    if second:
        tmp = tempfile.mkdtemp(dir=os.environ.get("TMPBUILD"))
        t2, g2 = os.path.join(tmp, "target"), os.path.join(tmp, "golden")
        B.run(t2)
        stamp(t2)
        os.makedirs(g2, exist_ok=True)
        goldens(t2, g2)
        stamp(g2)
        d1, d2 = digest(TARGET), digest(t2)
        assert d1 == d2, [f for f in d1 if d1[f] != d2.get(f)]
        assert digest(GOLDEN) == digest(g2), "golden differs between builds"
        shutil.rmtree(tmp)
        zp = cut_zip()
        print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
    return fig


if __name__ == "__main__":
    main(second="--once" not in sys.argv, checks="--nochecks" not in sys.argv)
