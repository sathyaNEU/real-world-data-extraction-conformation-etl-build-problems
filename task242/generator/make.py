"""Build the pack, compute every owed figure, write the goldens, figures.json, submission.md and metadata.json, run the
checks and the independent verifier, rebuild into a scratch folder and require byte-identical output, then cut
target.zip.

    python3 task242/generator/make.py            (full: two builds, the zip)
    python3 task242/generator/make.py --once     (one build, no zip)
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B
import estim as E
import golden as GD
import writeup as WU

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
STAMP = (2028, 1, 10, 7, 0, 0)        # the morning the pack was drawn


def metadata(target):
    files = []
    for k, f in B.FILES.items():
        p = os.path.join(target, f)
        rows = sum(1 for _ in open(p, encoding="utf-8")) - 1 if f.endswith(".csv") else None
        files.append({"path": f, "format": f.rsplit(".", 1)[1], "bytes": os.path.getsize(p), "rows": rows,
                      "source": "Constructed (seeded generator)", "date": "2028-01-10",
                      "license": "CC0-1.0 (original work)"})
    big = max((x for x in files if x["rows"]), key=lambda x: x["rows"])
    meta = {
        "task": "task242",
        "title": "Which of a city's 12 zones' published 2027 dengue infection shares, from its post-season IgM "
                 "household serosurvey, carry the misclassification flag, with each zone's November Breteau index and "
                 "the survey's household response rate",
        "domain": "Epidemiology & Public Health",
        "subdomain": "disease-surveillance-outbreak-anomaly-detection (a city's dengue serosurvey indicator judged against "
                     "the quality standard's misclassification flag: the share infected since 1 January estimated from "
                     "IgM results through the assay's detection by days since onset and each zone's epidemic curve)",
        "objective": "Data Quality Monitoring & Alerting",
        "prompt_shape": "07: a grid of zones against measures, each zone's published share, estimated share and flag "
                        "beside its November Breteau index and household response rate, and a slide of the shares "
                        "against the flag's limits",
        "as_of": "2028-01-10",
        "deliverables": [GD.XLSX, GD.PPTX],
        "distractor_files": [B.FILES[k] for k in B.DISTRACTORS],
        "stated_inputs": [],
        "field_terms": [],
        "input_gates": {"files": len(files), "formats": sorted({x["format"] for x in files}),
                        "largest_file": big["path"], "largest_file_rows": big["rows"]},
        "sources": [{"files": "all files under target/",
                     "origin": "generated by task242/generator/make.py (seeded, deterministic) around a fictional Indian "
                               "city corporation: its dengue line list, the 2027 household serosurvey's sample, field app "
                               "export, laboratory register and results, the medical college's kit verification panel, "
                               "the Vector Control Unit's November inspections and ward master, rainfall and fogging "
                               "records, and the corporation's register, SOPs, bulletin, protocol and emails; the city, "
                               "its zones, institutions and people are invented, and the epidemics are simulated, not "
                               "taken from any real dataset.",
                     "date": "2028-01-10", "license": "CC0-1.0 (original work)"}],
        "created": "2026-10-17",
        "generator": "task242/generator/make.py",
        "files": files,
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def stamp(folder):
    t = dt.datetime(*STAMP, tzinfo=dt.timezone.utc).timestamp()
    for f in os.listdir(folder):
        os.utime(os.path.join(folder, f), (t, t))


def digest(folder):
    return {f: hashlib.sha256(open(os.path.join(folder, f), "rb").read()).hexdigest() for f in sorted(os.listdir(folder))}


def cut_zip():
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(os.listdir(TARGET)):
            zi = zipfile.ZipInfo(f, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TARGET, f), "rb").read())
    return zp


def fresh(folder):
    if os.path.isdir(folder):
        for f in os.listdir(folder):
            os.remove(os.path.join(folder, f))
    os.makedirs(folder, exist_ok=True)


def main(second=True, checks=True):
    fresh(TARGET)
    o = B.run(TARGET)
    stamp(TARGET)
    X = E.solve(TARGET, B.FILES)
    A = WU.answers(X, B.FILES)
    fresh(GOLDEN)
    GD.write(GOLDEN, A)
    stamp(GOLDEN)
    fig = WU.write(TASK, HERE, A)
    metadata(TARGET)
    if checks:
        import checks as C
        n = C.run(TARGET, GOLDEN, o, X, A)
        print("checks: %d passed" % n)
        import verify as V
        V.main(TARGET, GOLDEN, os.path.join(HERE, "figures.json"), os.path.join(TASK, "submission.md"))
    if second:
        tmp = tempfile.mkdtemp(dir=os.environ.get("TMPBUILD"))
        t2, g2 = os.path.join(tmp, "target"), os.path.join(tmp, "golden")
        B.run(t2)
        stamp(t2)
        os.makedirs(g2, exist_ok=True)
        GD.write(g2, WU.answers(E.solve(t2, B.FILES), B.FILES))
        stamp(g2)
        d1, d2 = digest(TARGET), digest(t2)
        assert d1 == d2, [f for f in d1 if d1[f] != d2.get(f)]
        assert digest(GOLDEN) == digest(g2), "golden differs between builds"
        shutil.rmtree(tmp)
        zp = cut_zip()
        print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
    return A, fig


if __name__ == "__main__":
    main(second="--once" not in sys.argv, checks="--nochecks" not in sys.argv)
