"""Build the pack, compute every owed figure, write the goldens, figures.json, submission.md and metadata.json, run
the checks and the independent verifier, rebuild into a scratch folder and require byte-identical output, then cut
target.zip from the files under target/.

    python3 task200/generator/make.py            (full: two builds, the checks, the verifier, the zip)
    python3 task200/generator/make.py --once     (one build, checks and verifier, no zip)
"""
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B  # noqa: E402
import golden as GD  # noqa: E402
import pack as PK  # noqa: E402
import params as P  # noqa: E402
import solve as SV  # noqa: E402
import writeup as WU  # noqa: E402

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
AS_OF = "2027-01-15"
GOLDEN_STAMP = (2027, 1, 20, 16, 40, 0)


def walk(folder):
    return B.walk(folder)


def metadata(target):
    files = []
    for rel in walk(target):
        p = os.path.join(target, rel)
        rows = None
        if rel.endswith(".csv"):
            with open(p, encoding="utf-8") as fh:
                rows = sum(1 for _ in fh) - 1
            if rel.startswith("screening_tip/pierb"):
                rows -= 3
        files.append({"path": rel, "format": rel.rsplit(".", 1)[1], "bytes": os.path.getsize(p), "rows": rows,
                      "source": "Constructed (seeded generator, task200/generator/make.py)", "date": AS_OF,
                      "license": "CC0-1.0 (original work)"})
    big = max((x for x in files if x["rows"]), key=lambda x: x["rows"])
    meta = {
        "task": "task200",
        "title": "The order in which Brackenford Airport's screening teams go through the 2027 remedial X-ray image "
                 "interpretation course, the team whose X-ray operators are least likely to find a prohibited article "
                 "in a passenger's cabin bag first",
        "domain": "Human Factors & Ergonomics",
        "subdomain": "safety-incident-error-analysis (screener performance at an airport's security search)",
        "objective": "Anomaly Detection & Diagnostics",
        "prompt_shape": "06: a sequence under capacity, one screening team a course month, with each team's 2026 screen "
                        "time, clear searches and expiring certificates beside it, and a one-page note",
        "as_of": AS_OF,
        "deliverables": [GD.XLSX, GD.DOCX],
        "distractor_files": [PK.F[k] for k in PK.DISTRACTORS],
        "stated_inputs": ["31 December 2026", "1 July 2027"],
        "field_terms": [],
        "input_gates": {"files": len(files), "formats": sorted({x["format"] for x in files}),
                        "largest_file": big["path"], "largest_file_rows": big["rows"]},
        "sources": [{"files": "all files under target/",
                     "origin": "generated by task200/generator/make.py (seeded, deterministic) around a council-owned "
                               "regional airport's security screening: the Central Search CT system's threat image "
                               "projection exports and workstation sessions, the Pier B legacy X-ray screens' projection "
                               "log and screen events, the CT tray rejects, the search team's log, the screening roster, "
                               "the LMS assessment export, the assessment centre's certificates, the screener performance "
                               "standard, the course planning email, the lane throughput, queue time samples and the "
                               "compliance team's 2026 review; the airport, its teams, its systems, its suppliers and "
                               "its people are invented, and the records are simulated, not taken from any real dataset.",
                     "date": AS_OF, "license": "CC0-1.0 (original work)"}],
        "created": "2026-11-03",
        "generator": "task200/generator/make.py",
        "files": files,
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    return meta


def digest(folder):
    return {rel: hashlib.sha256(open(os.path.join(folder, rel), "rb").read()).hexdigest() for rel in walk(folder)}


def cut_zip():
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        dirs = ["target"] + sorted({"target/" + os.path.dirname(r) for r in walk(TARGET) if os.path.dirname(r)})
        for d in dirs:
            zi = zipfile.ZipInfo(d + "/", date_time=P.EXPORT_STAMP)
            zi.external_attr = (0o40755 << 16) | 0x10
            z.writestr(zi, b"")
        for rel in walk(TARGET):
            zi = zipfile.ZipInfo("target/" + rel, date_time=P.EXPORT_STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TARGET, rel), "rb").read())
    return zp


def fresh(folder):
    shutil.rmtree(folder, ignore_errors=True)
    os.makedirs(folder, exist_ok=True)


def main(second=True, checks=True):
    W = B.run(TARGET)
    S = SV.solve(TARGET)
    A = WU.answers(S)
    fresh(GOLDEN)
    GD.write(GOLDEN, A)
    B.stamp(GOLDEN, GOLDEN_STAMP)
    WU.write(TASK, HERE, A)
    metadata(TARGET)
    if checks:
        import checks as C
        n = C.run(TARGET, GOLDEN, W, S, A)
        for line in C.LOG:
            print("  " + line)
        print("checks: %d passed" % n)
        import verify as V
        V.main(TARGET, GOLDEN, os.path.join(HERE, "figures.json"), os.path.join(TASK, "submission.md"))
    if second:
        tmp = tempfile.mkdtemp(dir=os.environ.get("TMPBUILD"))
        t2, g2 = os.path.join(tmp, "target"), os.path.join(tmp, "golden")
        B.run(t2)
        GD.write(g2, WU.answers(SV.solve(t2)))
        B.stamp(g2, GOLDEN_STAMP)
        d1, d2 = digest(TARGET), digest(t2)
        assert d1 == d2, [f for f in d1 if d1[f] != d2.get(f)]
        g1, g2d = digest(GOLDEN), digest(g2)
        assert g1 == g2d, ("golden differs between builds", [f for f in g1 if g1[f] != g2d.get(f)])
        shutil.rmtree(tmp)
        zp = cut_zip()
        print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
    return A


if __name__ == "__main__":
    main(second="--once" not in sys.argv, checks="--nochecks" not in sys.argv)
