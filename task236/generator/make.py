"""Build the pack, compute every owed figure, write the goldens, figures.json, submission.md and metadata.json, run the
checks and the independent verifier, rebuild into a scratch folder and require byte-identical output, then cut
target.zip.

    python3 task236/generator/make.py            (full: two builds, the zip)
    python3 task236/generator/make.py --once     (one build, no zip)
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B
import estim as E
import golden as GD
import writeup as WU

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
STAMP = (2027, 9, 13, 20, 40, 0)          # 06:40 on Tuesday 14 September 2027, local (UTC+10)


def metadata(target):
    files = []
    for k, f in B.FILES.items():
        p = os.path.join(target, f)
        rows = sum(1 for _ in open(p, encoding="utf-8")) - 1 if f.endswith(".csv") else None
        files.append({"path": f, "format": f.rsplit(".", 1)[1], "bytes": os.path.getsize(p), "rows": rows,
                      "source": "Constructed (seeded generator)", "date": "2027-09-14", "license": "CC0-1.0 (original work)"})
    big = max((x for x in files if x["rows"]), key=lambda x: x["rows"])
    meta = {
        "task": "task236",
        "title": "Which of a state's eight health regions whose influenza testing changed in late July and August carry a "
                 "testing-change break flag on their notified influenza series in the week 36 report, each change judged "
                 "against the sentinel general practice network's influenza activity",
        "domain": "Epidemiology & Public Health",
        "subdomain": "disease-surveillance-outbreak-anomaly-detection (a state health department's weekly influenza report: "
                     "each region's notified series read against the sentinel network's influenza-like-illness "
                     "consultations attributed to influenza by its protocol swabs, across a change in the region's testing)",
        "objective": "Data Quality Monitoring & Alerting",
        "prompt_shape": "11: before and after with a control, eight health regions each with its notified series either "
                        "side of its testing change read against the sentinel network's influenza activity and flagged or "
                        "not under the data quality protocol's testing-change break rule, with each region's "
                        "season-to-date notified cases and week 36 notified rate per 100,000 residents as the week 36 "
                        "report counts them (30 criteria)",
        "as_of": "2027-09-14",
        "deliverables": [GD.XLSX, GD.PNG],
        "distractor_files": [B.FILES[k] for k in B.DISTRACTORS],
        "field_terms": [],
        "input_gates": {"files": len(files), "formats": sorted({x["format"] for x in files}),
                        "largest_file": big["path"], "largest_file_rows": big["rows"]},
        "sources": [{"files": "all files under target/",
                     "origin": "generated by task236/generator/make.py (seeded, deterministic) around a state health "
                               "department's communicable diseases branch, its notification gateway, sentinel general "
                               "practice network, testing change register and postcode concordance; the state, its regions, "
                               "postcodes, services and people are invented, no real person, service or patient is "
                               "depicted, and the interstate postcodes are real postcodes used only as residents' addresses.",
                     "date": "2027-09-14", "license": "CC0-1.0 (original work)"}],
        "created": "2026-10-17",
        "generator": "task236/generator/make.py",
        "files": files,
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2)
        fh.write("\n")


def stamp(folder):
    t = dt.datetime(*STAMP, tzinfo=dt.timezone.utc).timestamp()
    for f in os.listdir(folder):
        os.utime(os.path.join(folder, f), (t, t))


def digest(folder):
    return {f: hashlib.sha256(open(os.path.join(folder, f), "rb").read()).hexdigest() for f in sorted(os.listdir(folder))}


def cut_zip():
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(os.listdir(TARGET)):
            zi = zipfile.ZipInfo(f, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TARGET, f), "rb").read())
    return zp


def fresh(folder):
    if os.path.isdir(folder):
        for f in os.listdir(folder):
            os.remove(os.path.join(folder, f))
    os.makedirs(folder, exist_ok=True)


def main(second=True, checks=True):
    fresh(TARGET)
    o = B.run(TARGET)
    stamp(TARGET)
    X = E.solve(TARGET, B.FILES)
    A = WU.answers(X, B.FILES)
    fresh(GOLDEN)
    GD.write(GOLDEN, A)
    stamp(GOLDEN)
    fig = WU.write(TASK, HERE, A)
    metadata(TARGET)
    if checks:
        import checks as C
        n = C.run(TARGET, GOLDEN, o, X)
        print("checks: %d passed" % n)
        import verify as V
        V.main(TARGET, GOLDEN, os.path.join(HERE, "figures.json"), os.path.join(TASK, "submission.md"))
    if second:
        tmp = tempfile.mkdtemp(dir=os.environ.get("TMPBUILD"))
        t2, g2 = os.path.join(tmp, "target"), os.path.join(tmp, "golden")
        B.run(t2)
        stamp(t2)
        os.makedirs(g2, exist_ok=True)
        GD.write(g2, WU.answers(E.solve(t2, B.FILES), B.FILES))
        stamp(g2)
        d1, d2 = digest(TARGET), digest(t2)
        assert d1 == d2, [f for f in d1 if d1[f] != d2.get(f)]
        assert digest(GOLDEN) == digest(g2), "golden differs between builds"
        shutil.rmtree(tmp)
        zp = cut_zip()
        print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
    return A, fig


if __name__ == "__main__":
    main(second="--once" not in sys.argv, checks="--nochecks" not in sys.argv)
