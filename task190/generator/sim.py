"""The deposit population.

Amounts are drawn one at a time from the segment's own density, so every bin count is a genuine
sample and carries a sample's scatter. The density is one exponential decay across the stretch the
book's deposits cover, with a soft rise below it and a faster tail above, so neither end is a wall.
Counted cash lands on round figures, so a share of each draw snaps to the nearest fifty.

Splitting is generated by replacing a take: a deposit at or just above the prescribed threshold is
taken out of the record and paid in instead as two deposits on the same day, the larger inside
9,000 to 10,000. The dollars balance to the cent, so the surplus the band carries is matched by a
deficit of the same size in 10,000 to 11,000.
"""
import datetime as dt
import math

import world as W

MIN_AMT = 20.0              # a counted take smaller than this is not banked on its own
X0, X1 = 1500.0, 22000.0    # the stretch the one decay covers
ALPHA = 1.40                # how the density climbs out of zero below X0
TAIL = 4200.0               # the faster decay above X1
AMT_MAX = 90000.0
GRID = 10.0                 # the sampling grid the inverse CDF is built on
ROUND_SHARE = 0.46          # cash is counted in notes, so amounts snap to the nearest fifty
SNAP = 50.0
GROWTH = 1.058              # the book's cash volume, prior year to reporting year

# the cents a counted take comes to when it is not a round figure: coin is counted too
CENTS = ([0] * 26 + [50] * 9 + [25, 75] * 4 + [20, 40, 60, 80] * 3 +
         [10, 30, 70, 90] * 2 + [5, 15, 35, 45, 55, 65, 85, 95] +
         list(range(1, 100, 2)) + list(range(2, 100, 7)))


def shash(text):
    """A deterministic string hash: Python's own is salted per process."""
    h = 2166136261
    for ch in text:
        h = ((h ^ ord(ch)) * 16777619) & 0xFFFFFFFF
    return h


class Rng(object):
    """A small deterministic generator, so a rebuild is byte-identical."""

    def __init__(self, seed):
        self.s = (seed * 6364136223846793005 + 1442695040888963407) & ((1 << 64) - 1)

    def next(self):
        self.s = (self.s * 6364136223846793005 + 1442695040888963407) & ((1 << 64) - 1)
        return (self.s >> 11) & ((1 << 53) - 1)

    def u(self):
        return self.next() / float(1 << 53)

    def below(self, n):
        return self.next() % n if n else 0

    def pick(self, seq):
        return seq[self.below(len(seq))]

    def shuffle(self, seq):
        for i in range(len(seq) - 1, 0, -1):
            j = self.below(i + 1)
            seq[i], seq[j] = seq[j], seq[i]
        return seq


def density(scale, x):
    """Deposits per dollar at amount x, up to a constant. Log-linear in x across X0 to X1, which
    is the whole of the stretch any of the reporting windows looks at."""
    if x <= MIN_AMT:
        return 0.0
    if x < X0:
        return math.exp(-X0 / scale) * ((x - MIN_AMT) / (X0 - MIN_AMT)) ** ALPHA
    if x <= X1:
        return math.exp(-x / scale)
    return math.exp(-X1 / scale) * math.exp(-(x - X1) / TAIL)


_CDF = {}


def _cdf(scale):
    """The density's running integral on the sampling grid, cached per segment."""
    if scale not in _CDF:
        xs, cum, tot = [], [], 0.0
        x = 0.0
        while x < AMT_MAX:
            tot += density(scale, x + GRID / 2.0) * GRID
            xs.append(x + GRID)
            cum.append(tot)
            x += GRID
        _CDF[scale] = (xs, [c / tot for c in cum])
    return _CDF[scale]


def draw(scale, rng):
    """One deposit amount: the density inverted, then snapped to a round figure or left ragged."""
    xs, cum = _cdf(scale)
    u = rng.u()
    lo, hi = 0, len(cum) - 1
    while lo < hi:
        mid = (lo + hi) // 2
        if cum[mid] < u:
            lo = mid + 1
        else:
            hi = mid
    prev = cum[lo - 1] if lo else 0.0
    span = cum[lo] - prev
    x = xs[lo] - GRID + (GRID * (u - prev) / span if span > 0 else GRID * rng.u())
    if rng.u() < ROUND_SHARE:
        return round(SNAP * math.floor(x / SNAP + 0.5), 2)
    return round(math.floor(x) + rng.pick(CENTS) / 100.0, 2)


def dates(lo, hi):
    a = dt.date(*[int(v) for v in lo.split("-")])
    b = dt.date(*[int(v) for v in hi.split("-")])
    out = []
    while a <= b:
        out.append(a)
        a += dt.timedelta(days=1)
    return out


# How a segment's customers trade: the share of deposits that land on a day the
# customer already paid in, and how much cash a trading day is worth.
TRADE = {
    "GRO": dict(pair=0.72, weekend=0.84, machine=0.58),
    "HOS": dict(pair=0.61, weekend=0.92, machine=0.44),
    "TRA": dict(pair=0.24, weekend=0.21, machine=0.31),
    "CON": dict(pair=0.19, weekend=0.14, machine=0.26),
    "RUR": dict(pair=0.27, weekend=0.33, machine=0.22),
    "FUE": dict(pair=0.78, weekend=0.88, machine=0.63),
    "PER": dict(pair=0.22, weekend=0.47, machine=0.35),
    "CLB": dict(pair=0.34, weekend=0.74, machine=0.29),
}


def customers(seed=19027):
    """The business banking book: one row per customer, with its own trading weight."""
    rng = Rng(seed)
    out = []
    n = 0
    for key, name, ndep, scale, ncust, plant, pplant in W.SEGMENTS:
        for i in range(ncust):
            n += 1
            # a skewed trading weight: a few customers pay in many times, most rarely
            u = rng.u()
            weight = 0.25 + 7.5 * (u ** 3.2)
            br = rng.pick([b[0] for b in W.BRANCHES])
            opened = dt.date(2016, 1, 4) + dt.timedelta(days=rng.below(3800))
            out.append(dict(cust="AB%06d" % (100000 + n * 7 + rng.below(5)),
                            seg=key, branch=br, weight=weight,
                            opened=opened.isoformat(),
                            pair=TRADE[key]["pair"], machine=TRADE[key]["machine"],
                            weekend=TRADE[key]["weekend"]))
    seen, uniq = set(), []
    for c in out:
        while c["cust"] in seen:
            c["cust"] = "AB%06d" % (int(c["cust"][2:]) + 1)
        seen.add(c["cust"])
        uniq.append(c)
    return uniq


def _slots(custs, days, total, rng):
    """Deal `total` deposit slots out over customers and days, skewed by trading weight."""
    wsum = sum(c["weight"] for c in custs)
    slots = []
    for c in custs:
        share = c["weight"] / wsum
        k = int(total * share)
        if rng.u() < total * share - k:
            k += 1
        for _ in range(k):
            d = rng.pick(days)
            while d.weekday() >= 5 and rng.u() > c["weekend"]:
                d = rng.pick(days)
            slots.append([c["cust"], d, "machine" if rng.u() < c["machine"] else "counter"])
    # the pairing habit: a share of slots is moved onto a day the customer already used
    byc = {}
    for s in slots:
        byc.setdefault(s[0], []).append(s)
    pair = {c["cust"]: c["pair"] for c in custs}
    for cust, ss in byc.items():
        used = sorted({s[1] for s in ss})
        if not used:
            continue
        for s in ss:
            if rng.u() < pair[cust]:
                s[1] = used[rng.below(len(used))]
    rng.shuffle(slots)
    return slots


def build(seed=4471):
    """Every cash deposit of both reporting years, and the planted structuring events."""
    custs = customers()
    bycust = {c["cust"]: c for c in custs}
    byseg = {}
    for c in custs:
        byseg.setdefault(c["seg"], []).append(c)

    rows = []           # dicts: cust, date, channel, amount, year, planted
    truth = {}          # (year, seg) -> planted count
    for year, (lo, hi), vol in (("2027", (W.YEAR_LO, W.YEAR_HI), 1.0),
                                ("2026", (W.PRIOR_LO, W.PRIOR_HI), 1.0 / GROWTH)):
        days = dates(lo, hi)
        for key, name, ndep, scale, ncust, plant, pplant in W.SEGMENTS:
            rng = Rng(seed + shash(key + year) % 100000)
            amts = [draw(scale, rng) for _ in range(int(round(ndep * vol)))]
            slots = _slots(byseg[key], days, len(amts), rng)
            while len(slots) < len(amts):
                c = rng.pick(byseg[key])
                slots.append([c["cust"], rng.pick(days), "counter"])
            for amt, (cust, day, chan) in zip(amts, slots):
                rows.append(dict(cust=cust, date=day, channel=chan, amount=amt,
                                 year=year, planted=0))
            truth[(year, key)] = plant if year == "2027" else pplant

    # Plant the structuring events. A customer whose cash take for the day was at or above the
    # prescribed threshold paid it in as two deposits instead of one: the larger inside
    # 9,000 to 10,000, the remainder beside it on the same day. The take itself is taken OUT of
    # the record, so the dollars balance to the cent and the surplus the band carries is matched
    # by a deficit of the same size in 10,000 to 11,000, where the takes would have sat. Nothing
    # is added anywhere else, so each segment's profile away from those two intervals is its
    # ordinary trade and nothing else.
    # where the larger of the two lands: round figures just under the threshold, and ragged ones
    PILES = [(9900.0, 0.19), (9950.0, 0.13), (9800.0, 0.10), (9500.0, 0.07), (9750.0, 0.05),
             (9700.0, 0.04), (9600.0, 0.03), (9850.0, 0.03)]
    MIN_REST = 200.0
    planted_rows = []
    drop = set()
    for year in ("2027", "2026"):
        for key, name, ndep, scale, ncust, plant, pplant in W.SEGMENTS:
            want = plant if year == "2027" else pplant
            rng = Rng(seed + 991 + shash(key + year + "p") % 100000)
            # the customers who split are cash-heavy ones: the quartile that pays in most
            heavy = sorted(byseg[key], key=lambda c: (-c["weight"], c["cust"]))
            pool = {c["cust"] for c in heavy[:max(40, (len(heavy) * 4) // 5)]}
            # the takes that would have been reported: one deposit, just over the threshold
            cand = [i for i, r in enumerate(rows)
                    if r["year"] == year and r["cust"] in pool
                    and W.THRESHOLD <= r["amount"] < W.THRESHOLD + 1000.0]
            rng.shuffle(cand)
            made = 0
            for i in cand:
                if made >= want:
                    break
                r = rows[i]
                cf = r["amount"]
                u = rng.u()
                acc, amt = 0.0, None
                for v, w in PILES:
                    acc += w
                    if u <= acc and v <= cf - MIN_REST:
                        amt = v
                        break
                if amt is None:                       # the ragged ones
                    hi = min(cf - MIN_REST, W.THRESHOLD - 0.05)
                    if hi < W.BAND_LO:
                        continue
                    amt = round(W.BAND_LO + rng.below(int((hi - W.BAND_LO) * 20) + 1) / 20.0, 2)
                rest = round(cf - amt, 2)
                if rest < MIN_REST or amt < W.BAND_LO or amt >= W.THRESHOLD:
                    continue
                drop.add(i)
                planted_rows.append(dict(cust=r["cust"], date=r["date"],
                                         channel=r["channel"], amount=amt,
                                         year=year, planted=1))
                planted_rows.append(dict(cust=r["cust"], date=r["date"],
                                         channel="machine" if rng.u() < 0.42 else "counter",
                                         amount=rest, year=year, planted=0))
                made += 1
            truth[(year, key)] = made
    rows = [r for i, r in enumerate(rows) if i not in drop]
    rows.extend(planted_rows)
    rows.sort(key=lambda r: (r["year"], r["date"], r["cust"], r["amount"]))
    return custs, bycust, rows, truth
