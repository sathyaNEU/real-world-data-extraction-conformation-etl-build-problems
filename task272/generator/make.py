"""Build the pack, compute every owed figure from it, write the goldens, figures.json, submission.md and
metadata.json, rebuild into a scratch folder and require byte-identical output, cut target.zip, then run the checks
and the independent verifier on the cut.

    python3 task272/generator/make.py
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import figs as F       # noqa: E402
import golden as GD    # noqa: E402
import pack as K       # noqa: E402
import writeup as WU   # noqa: E402

TASK = os.path.dirname(HERE)
STAMP = (2027, 1, 18, 9, 30, 0)

SOURCES = {
    "doses": "a hospital pharmacy server's export of its compounders' dose records (one row per fill)",
    "events": "the compounders' event export (set-ups, calibrations and alarms)",
    "checks": "a sterile compounding unit's gravimetric check register, one sheet per quarter",
    "quarantine": "a sterile compounding unit's quarantine register of in-process sorts",
    "master": "a compounded product master (volumes, tolerances, specific gravities, tares, stations)",
    "equipment": "a compounding equipment register (stations, serials, service dates)",
    "policy": "a hospital pharmacy's policy on gravimetric verification of batch-compounded products",
    "sop": "a sterile compounding unit's batch compounding procedure",
    "request": "an IV workflow project lead's request for the product list at cutover",
    "gc1": "a gravimetric compounder's every-dose weight record",
    "wards": "a pharmacy's doses issued to wards by month",
    "cleanroom": "a sterile compounding unit's cleanroom environmental monitoring",
}


def metadata():
    meta = {"task": "task272", "architecture": 3,
            "files": {K.FILES[k]: {"role": "distractor" if k in K.DISTRACTORS else "evidence",
                                   "source": "synthetic, generated by the task's seeded generator",
                                   "describes": SOURCES[k], "date": "2027-01-18", "license": "CC0-1.0"}
                      for k in K.FILES},
            "distractors": [K.FILES[k] for k in K.DISTRACTORS],
            "deliverables": [GD.PDF, GD.CSV]}
    with open(os.path.join(TASK, "metadata.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=1, ensure_ascii=False)
        f.write("\n")


def build(root):
    target = os.path.join(root, "target")
    golden = os.path.join(root, "golden")
    for d in (target, golden):
        if os.path.exists(d):
            shutil.rmtree(d)
    K.build(target)
    fig, _ = F.compute(target)
    with open(os.path.join(root, "figures.json"), "w", encoding="utf-8") as f:
        json.dump(fig, f, indent=1, sort_keys=True)
        f.write("\n")
    with tempfile.TemporaryDirectory() as tmp:
        GD.write_all(target, golden, fig, tmp)
    WU.write(os.path.join(root, "submission.md"), fig)
    return fig


def digest(root):
    out = {}
    for sub in ("target", "golden"):
        for fn in sorted(os.listdir(os.path.join(root, sub))):
            out[sub + "/" + fn] = hashlib.sha256(open(os.path.join(root, sub, fn), "rb").read()).hexdigest()
    for fn in ("figures.json", "submission.md"):
        p = os.path.join(root, fn) if os.path.exists(os.path.join(root, fn)) else os.path.join(HERE, fn)
        out[fn] = hashlib.sha256(open(p, "rb").read()).hexdigest()
    return out


def main():
    fig = build(TASK)
    shutil.move(os.path.join(TASK, "figures.json"), os.path.join(HERE, "figures.json"))
    metadata()
    import world as W
    W._CACHE.clear()
    with tempfile.TemporaryDirectory() as tmp:
        build(tmp)
        a = digest(TASK)
        a["figures.json"] = hashlib.sha256(open(os.path.join(HERE, "figures.json"), "rb").read()).hexdigest()
        b = digest(tmp)
        diff = [k for k in a if a[k] != b.get(k)]
        if diff:
            print("NOT byte-identical:", diff)
            return 1
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for fn in sorted(K.FILES.values()):
            zi = zipfile.ZipInfo(fn, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TASK, "target", fn), "rb").read())
    print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
    print("call", fig["call"])
    print("ladder", fig["ladder"])
    rc = subprocess.call([sys.executable, os.path.join(HERE, "checks.py")])
    rc |= subprocess.call([sys.executable, os.path.join(HERE, "verify.py")])
    return rc


if __name__ == "__main__":
    sys.exit(main())
