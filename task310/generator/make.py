"""Build the pack, compute every owed figure from it, write the goldens, figures.json, submission.md and metadata.json,
run the checks, rebuild into a scratch folder and require byte-identical output, cut target.zip and run the independent
verifier on it.

    python3 task310/generator/make.py            (full: two builds, the zip, the verifier)
    python3 task310/generator/make.py --once     (one build, no zip)
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B  # noqa: E402
import figs as FG  # noqa: E402
import golden as GD  # noqa: E402
import params as P  # noqa: E402
import writeup as WU  # noqa: E402

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
STAMP = (2026, 11, 9, 16, 48, 0)        # the afternoon the brief's pack was put together


