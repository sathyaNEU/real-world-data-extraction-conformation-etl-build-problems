"""Build the pack, compute every owed figure from it, write the goldens, figures.json, submission.md and metadata.json,
rebuild into a scratch folder and require byte-identical output, cut target.zip, then run the checks and the
independent verifier on the cut.

    python3 task474/generator/make.py
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import figs as F       # noqa: E402
import golden as GD    # noqa: E402
import pack as K       # noqa: E402
import writeup as WU   # noqa: E402

TASK = os.path.dirname(HERE)
STAMP = (2026, 10, 12, 7, 0, 0)

SOURCES = {
    "brindle": "a test vendor's results export for an awarding body's paper (one row per booked sitting)",
    "harrowgate": "a second test vendor's sittings export with proctor-review records",
    "register": "an awarding body's candidate register tying board numbers to the vendors' candidate numbers",
    "ap3": "an awarding body's assessment policy on pass marks and standards",
    "notice": "an awarding body's notice of a change of paper and provider",
    "request": "the Head of Qualifications' request for the Board paper",
    "providers": "an awarding body's list of approved training providers",
    "venues": "the vendors' test centres and sites",
    "items": "the new vendor's item statistics for the paper",
    "feedback": "an awarding body's candidate feedback survey",
}


def metadata():
    meta = {"task": "task474", "architecture": 7,
            "files": {K.FILES[k]: {"role": "distractor" if k in K.DISTRACTORS else "evidence",
                                   "source": "synthetic, generated by task474/generator (seeded)",
                                   "describes": SOURCES[k], "date": "2026-10-12", "license": "CC0-1.0"}
                      for k in K.FILES},
            "distractors": [K.FILES[k] for k in K.DISTRACTORS],
            "deliverables": [GD.PDF, GD.CSV]}
    with open(os.path.join(TASK, "metadata.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=1, ensure_ascii=False)
        f.write("\n")


def build(root):
    target = os.path.join(root, "target")
    golden = os.path.join(root, "golden")
    for d in (target, golden):
        if os.path.exists(d):
            shutil.rmtree(d)
    K.build(target)
    fig = F.compute(target)
    with open(os.path.join(root, "figures.json"), "w", encoding="utf-8") as f:
        json.dump(fig, f, indent=1, sort_keys=True)
        f.write("\n")
    GD.write_all(target, golden, fig)
    WU.write(os.path.join(root, "submission.md"), fig)
    return fig


def digest(root):
    out = {}
    for sub in ("target", "golden"):
        for fn in sorted(os.listdir(os.path.join(root, sub))):
            out[sub + "/" + fn] = hashlib.sha256(open(os.path.join(root, sub, fn), "rb").read()).hexdigest()
    for fn in ("figures.json", "submission.md"):
        p = os.path.join(root, fn) if os.path.exists(os.path.join(root, fn)) else os.path.join(HERE, fn)
        out[fn] = hashlib.sha256(open(p, "rb").read()).hexdigest()
    return out


def main():
    fig = build(TASK)
    shutil.move(os.path.join(TASK, "figures.json"), os.path.join(HERE, "figures.json"))
    metadata()
    with tempfile.TemporaryDirectory() as tmp:
        build(tmp)
        a = digest(TASK)
        a["figures.json"] = hashlib.sha256(open(os.path.join(HERE, "figures.json"), "rb").read()).hexdigest()
        b = digest(tmp)
        diff = [k for k in a if a[k] != b.get(k)]
        if diff:
            print("NOT byte-identical:", diff)
            return 1
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for fn in sorted(K.FILES.values()):
            zi = zipfile.ZipInfo(fn, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TASK, "target", fn), "rb").read())
    print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
    print("call", fig["call"])
    print("ladder", fig["ladder"])
    rc = subprocess.call([sys.executable, os.path.join(HERE, "checks.py")])
    rc |= subprocess.call([sys.executable, os.path.join(HERE, "verify.py")])
    return rc


if __name__ == "__main__":
    sys.exit(main())
