"""Build the pack, compute every owed figure, write the goldens, figures.json, submission.md and metadata.json, run the
checks and the independent verifier, rebuild into a scratch folder and require byte-identical output, then cut
target.zip.

    python3 task238/generator/make.py            (full: two builds, the zip)
    python3 task238/generator/make.py --once     (one build, no zip)
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B
import estim as E
import golden as GD
import writeup as WU

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
STAMP = (2027, 10, 17, 21, 30, 0)        # 10:30 on Monday 18 October 2027, Halvreth time (UTC+13)


def metadata(target):
    files = []
    for k, f in B.FILES.items():
        p = os.path.join(target, f)
        rows = sum(1 for _ in open(p, encoding="utf-8")) - 1 if f.endswith(".csv") else None
        files.append({"path": f, "format": f.rsplit(".", 1)[1], "bytes": os.path.getsize(p), "rows": rows,
                      "source": "Constructed (seeded generator)", "date": "2027-10-18", "license": "CC0-1.0 (original work)"})
    big = max((x for x in files if x["rows"]), key=lambda x: x["rows"])
    meta = {
        "task": "task238",
        "title": "The band at which a household wellbeing tracker's mode-mix monitor runs once the tracker goes "
                 "web-first, each headline index's mode effect read through a randomized contact strategy test",
        "domain": "Survey Research & Official Statistics",
        "subdomain": "nonresponse-calibration-measurement-error-adjustment (a national statistics office's continuity "
                     "standard for its quarterly wellbeing tracker: the widest whole-point departure of a quarter's web "
                     "share that keeps every headline index's mode-mix artefact within its tolerance, from each index's "
                     "mode effect measured on the 2027 contact strategy test)",
        "objective": "Data Quality Monitoring & Alerting",
        "prompt_shape": "04: setting one dial, the monitor's band, with the test's response rate under each letter in "
                        "each quarter, each headline index's valid answers online and by telephone, and a chart of each "
                        "index's widest band against the band",
        "as_of": "2027-10-20",
        "deliverables": [GD.XLSX, GD.PNG],
        "distractor_files": [B.FILES[k] for k in B.DISTRACTORS],
        "field_terms": [],
        "input_gates": {"files": len(files), "formats": sorted({x["format"] for x in files}),
                        "largest_file": big["path"], "largest_file_rows": big["rows"]},
        "sources": [{"files": "all files under target/",
                     "origin": "generated by task238/generator/make.py (seeded, deterministic) around a national "
                               "statistics office's continuity standard, a contact strategy test's plan, close-out and "
                               "exports, and a questionnaire codebook; the office, the tracker, the island state, its "
                               "regions and the people are invented, and no real respondent is depicted.",
                     "date": "2027-10-18", "license": "CC0-1.0 (original work)"}],
        "created": "2026-10-17",
        "generator": "task238/generator/make.py",
        "files": files,
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2)
        fh.write("\n")


def stamp(folder):
    t = dt.datetime(*STAMP, tzinfo=dt.timezone.utc).timestamp()
    for f in os.listdir(folder):
        os.utime(os.path.join(folder, f), (t, t))


def digest(folder):
    return {f: hashlib.sha256(open(os.path.join(folder, f), "rb").read()).hexdigest() for f in sorted(os.listdir(folder))}


def cut_zip():
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(os.listdir(TARGET)):
            zi = zipfile.ZipInfo(f, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TARGET, f), "rb").read())
    return zp


def fresh(folder):
    if os.path.isdir(folder):
        for f in os.listdir(folder):
            os.remove(os.path.join(folder, f))
    os.makedirs(folder, exist_ok=True)


def main(second=True, checks=True):
    fresh(TARGET)
    o = B.run(TARGET)
    stamp(TARGET)
    X = E.solve(TARGET, B.FILES)
    A = WU.answers(X, B.FILES)
    fresh(GOLDEN)
    GD.write(GOLDEN, A)
    stamp(GOLDEN)
    fig = WU.write(TASK, HERE, A)
    metadata(TARGET)
    if checks:
        import checks as C
        n = C.run(TARGET, GOLDEN, o, X)
        print("checks: %d passed" % n)
        import verify as V
        V.main(TARGET, GOLDEN, os.path.join(HERE, "figures.json"), os.path.join(TASK, "submission.md"))
    if second:
        tmp = tempfile.mkdtemp(dir=os.environ.get("TMPBUILD"))
        t2, g2 = os.path.join(tmp, "target"), os.path.join(tmp, "golden")
        B.run(t2)
        stamp(t2)
        os.makedirs(g2, exist_ok=True)
        GD.write(g2, WU.answers(E.solve(t2, B.FILES), B.FILES))
        stamp(g2)
        d1, d2 = digest(TARGET), digest(t2)
        assert d1 == d2, [f for f in d1 if d1[f] != d2.get(f)]
        assert digest(GOLDEN) == digest(g2), "golden differs between builds"
        shutil.rmtree(tmp)
        zp = cut_zip()
        print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
    return A, fig


if __name__ == "__main__":
    main(second="--once" not in sys.argv, checks="--nochecks" not in sys.argv)
