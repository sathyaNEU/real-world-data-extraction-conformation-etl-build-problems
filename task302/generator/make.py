"""Build the pack, compute every owed figure from it, write the goldens, figures.json, submission.md and metadata.json,
run the checks, rebuild into a scratch folder and require byte-identical output, cut target.zip and run the independent
verifier on it.

    python3 task302/generator/make.py            (full: two builds, the zip, the verifier)
    python3 task302/generator/make.py --once     (one build, no zip)
"""
import datetime as dt
import hashlib
import json
import os
import shutil
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build as B
import figs as FG
import golden as GD
import params as P
import writeup as WU

TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
GOLDEN = os.path.join(TASK, "golden")
STAMP = (2026, 11, 16, 16, 5, 0)         # the afternoon the store ordering folder was put together


def metadata(target):
    files = []
    for k in B.PACK:
        f = B.FILES[k]
        p = os.path.join(target, f)
        rows = (sum(1 for _ in open(p, encoding="utf-8")) - 1) if f.endswith(".csv") else None
        if f.endswith(".xlsx") or f.endswith(".docx"):
            rows = None
        if f.endswith(".parquet"):
            import pyarrow.parquet as pq
            rows = pq.ParquetFile(p).metadata.num_rows
        files.append({"path": f, "format": f.rsplit(".", 1)[1], "bytes": os.path.getsize(p), "rows": rows,
                      "source": "Constructed (seeded generator)", "date": P.AS_OF.isoformat(),
                      "license": "CC0-1.0 (original work)"})
    big = max((x for x in files if x["rows"]), key=lambda x: x["rows"])
    meta = {
        "task": "task302",
        "title": "Which of four categories a regional supermarket chain moves first onto automated store ordering in "
                 "2027, by what the move adds to the category's sales, with the cereal trial, the distribution centre's "
                 "late deliveries and the pallets its suppliers delivered",
        "domain": "Economics & Econometrics",
        "subdomain": "structural-equilibrium-modeling (structural demand: where an unavailable product's demand goes, "
                     "to the category's other lines on the day and to the line itself after the restock)",
        "objective": "Opportunity Sizing & Decision Support",
        "prompt_shape": "other: one of four categories and its addition, with a chart of the four, and three asks on "
                        "the cereal trial export, the distribution centre's trailer stops and its purchasing",
        "as_of": P.AS_OF.isoformat(),
        "deliverables": [GD.DECK, GD.XLSX],
        "distractor_files": [B.FILES[k] for k in B.DISTRACTORS],
        "context_artifacts": [B.FILES[k] for k in B.CONTEXT],
        "stated_inputs": ["the value of going first: what the category would have sold in the 24 stores over the "
                          "twelve months to 30 June 2026 had half of its out-of-stock line-days not happened, less what "
                          "it did sell, at each line's 2025-26 shelf price (planning note)",
                          "a line-day is out of stock when the store opened with none of the line on hand, as the stock "
                          "system's opening position records it (planning note)"],
        "field_terms": [],
        "input_gates": {"files": len(files), "formats": sorted({x["format"] for x in files}),
                        "largest_file": big["path"], "largest_file_rows": big["rows"]},
        "sources": [{"files": "all files under target/",
                     "origin": "generated by task302/generator/make.py (seeded, deterministic) around a fictional "
                               "New Zealand supermarket chain of 24 stores with its own distribution centre: each "
                               "store-line-day's first-choice demand in four categories, out-of-stock spells from "
                               "missed store orders and from the formula supplier's missed weekly visits, shoppers who "
                               "take another line, come back after the restock or buy nothing, the tills' sales and "
                               "returns through a code migration, the stock system's opening positions, a cereal "
                               "trial of an ordering system, the distribution centre's trailer stops and purchasing; "
                               "every organisation, store, product and person is invented, and no real dataset is "
                               "reproduced.",
                     "date": P.AS_OF.isoformat(), "license": "CC0-1.0 (original work)"}],
        "created": "2026-10-25",
        "generator": "task302/generator/make.py",
        "files": files,
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as fh:
        json.dump(meta, fh, indent=2, ensure_ascii=False)
        fh.write("\n")


def stamp(folder):
    t = dt.datetime(*STAMP, tzinfo=dt.timezone.utc).timestamp()
    for f in os.listdir(folder):
        os.utime(os.path.join(folder, f), (t, t))


def digest(folder):
    return {f: hashlib.sha256(open(os.path.join(folder, f), "rb").read()).hexdigest() for f in sorted(os.listdir(folder))}


def cut_zip():
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(os.listdir(TARGET)):
            zi = zipfile.ZipInfo(f, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TARGET, f), "rb").read())
    return zp


def fresh(folder):
    if os.path.isdir(folder):
        for f in os.listdir(folder):
            os.remove(os.path.join(folder, f))
    os.makedirs(folder, exist_ok=True)


def main(second=True, checks=True):
    fresh(TARGET)
    R = B.build(TARGET)
    stamp(TARGET)
    fresh(GOLDEN)
    F, X = FG.compute(TARGET)
    F = json.loads(json.dumps(F))
    with open(os.path.join(HERE, "figures.json"), "w") as fh:
        json.dump(F, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    GD.write(GOLDEN, F, X)
    stamp(GOLDEN)
    WU.write(os.path.join(TASK, "submission.md"), F)
    metadata(TARGET)
    if checks:
        import checks as C
        assert not C.main(TARGET, R)
    if second:
        tmp = tempfile.mkdtemp()
        t2, g2 = os.path.join(tmp, "target"), os.path.join(tmp, "golden")
        B.build(t2)
        stamp(t2)
        F2, X2 = FG.compute(t2)
        F2 = json.loads(json.dumps(F2))
        GD.write(g2, F2, X2)
        stamp(g2)
        d1, d2 = digest(TARGET), digest(t2)
        assert d1 == d2, [f for f in d1 if d1[f] != d2.get(f)]
        assert digest(GOLDEN) == digest(g2), [f for f in digest(GOLDEN) if digest(GOLDEN)[f] != digest(g2).get(f)]
        assert F == F2
        shutil.rmtree(tmp)
        zp = cut_zip()
        print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
        import verify as V
        assert not V.main(zp)
    return F


if __name__ == "__main__":
    main(second="--once" not in sys.argv, checks="--nochecks" not in sys.argv)
