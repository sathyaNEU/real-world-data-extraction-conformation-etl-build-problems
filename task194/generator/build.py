"""Cut the bundle, compute the goldens from it, write figures.json and metadata.json, then check and verify."""
import json
import os
import shutil
import subprocess
import sys
import time

import numpy as np

import deliver
import docs
import golden as G
import pack as PK
import sim
import world as W

HERE = os.path.dirname(os.path.abspath(__file__))
TASK = os.path.dirname(HERE)
TARGET = os.path.join(TASK, "target")
STAMP = time.mktime((2026, 11, 3, 6, 12, 0, 0, 0, 0))


def cut(target):
    if os.path.isdir(target):
        shutil.rmtree(target)
    os.makedirs(target)
    rng = np.random.default_rng(W.SEED)
    S = sim.run(rng)
    r2 = np.random.default_rng(W.SEED + 1)
    rows = PK.write_flows(target, S, r2)
    PK.write_pressure(target, S, r2)
    PK.write_register(target, S)
    ex = PK.write_amr(target, S, r2)
    PK.write_accounts(target, S, ex)
    ev, _ = PK.billing(np.random.default_rng(W.SEED + 2))
    PK.write_billing(target, ev)
    assets = PK.assets(np.random.default_rng(W.SEED + 3))
    jobs, _ = PK.works(np.random.default_rng(W.SEED + 4), assets)
    PK.write_works(target, jobs)
    PK.write_assets(target, assets)
    PK.write_valves(target, np.random.default_rng(W.SEED + 6))
    PK.write_prv(target)
    PK.write_distractors(target, np.random.default_rng(W.SEED + 7))
    docs.build(os.path.join(target, PK.FILES["procedure"]))
    for fn in os.listdir(target):
        os.utime(os.path.join(target, fn), (STAMP, STAMP))
    return S, rows


def metadata():
    md = {
        "task": "task194",
        "decision": "where Arnvale Water's leak detection crew works in week 46 of 2026",
        "deliverables": ["crew_allocation_week46.xlsx", "night_flow_changes.pdf"],
        "distractor_files": ["target/" + PK.FILES[k] for k in PK.DISTRACTORS],
        "files": {},
    }
    desc = {
        "flows": "SCADA historian export of inlet meter readings, 15-minute, UTC",
        "pressure": "AZNP pressure logger export, hourly means",
        "register": "DMA register issue 14 with supply points and instrument units",
        "amr": "AMR head-end hourly register reads for logged large users",
        "accounts": "billing system large user account list",
        "billing": "billing system account event extract",
        "works": "works management system task export",
        "assets": "mains asset list from the asset register",
        "valves": "GIS export of boundary valves",
        "prv": "PRV set point change log",
        "procedure": "Leakage Procedure LP04 rev 3",
        "rain": "site rain gauge daily totals",
        "contacts": "customer contact log extract",
        "findfix": "find and fix crew outcomes 2025-26",
    }
    for k, fn in PK.FILES.items():
        md["files"]["target/" + fn] = {"source": "constructed for this task (fictional organisation)", "date": "2026-11-03",
                                      "licence": "CC BY 4.0 (task author)", "covers": desc[k],
                                      "made": "generated by task194/generator from a fixed seed"}
    return md


def main():
    S, rows = cut(TARGET)
    res = G.compute(TARGET)
    os.makedirs(os.path.join(TASK, "golden"), exist_ok=True)
    figs = deliver.write(res, os.path.join(TASK, "golden"))
    figs["constants"] = {"crew_week": 46, "lp04_clauses": [4.2, 4.3, 5.1], "N1": W.N1, "register_rollover_m3": 100000}
    json.dump(figs, open(os.path.join(HERE, "figures.json"), "w"), indent=1, sort_keys=True)
    json.dump(metadata(), open(os.path.join(TASK, "metadata.json"), "w"), indent=1)
    print("flows rows", rows, "call", figs["call"], "runner_up", figs["runner_up"])


if __name__ == "__main__":
    main()
