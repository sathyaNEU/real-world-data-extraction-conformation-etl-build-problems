"""Build task258: the evidence pack into <task>/target, the goldens into <task>/golden, metadata.json and
generator/figures.json, then the checks and the independent verifier, then a second full build into a scratch folder
inside the task (removed after) compared byte for byte, then target.zip cut from the final build.

    python3 task258/generator/build.py              everything
    python3 task258/generator/build.py --out DIR    the pack only, into DIR"""
import os
for _v in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_v, "1")
import argparse      # noqa: E402
import datetime as dt  # noqa: E402
import hashlib       # noqa: E402
import json          # noqa: E402
import shutil        # noqa: E402
import sys           # noqa: E402
import tempfile      # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import asks as A           # noqa: E402
import common as K         # noqa: E402
import docs as D           # noqa: E402
import postprocess as PP   # noqa: E402
import records as R        # noqa: E402
import world as W          # noqa: E402

TASK = os.path.dirname(HERE)
NAMES = {"charter": K.CHARTER, "beacons": K.BEACONS, "sampling": K.SAMPLING_CFG, "log": K.ENG_LOG,
         "eng": K.ENG_BEACONS, "runbook": K.RUNBOOK, "hosts": K.CDN_HOSTS, "notes": K.NOTES, "crux": K.CRUX,
         "analytics": K.ANALYTICS, "img": K.IMG_LOGS, "legacy": K.LEGACY_LOGS, "avif": K.AVIF_TABLE,
         "contract": K.CONTRACT, "dam": K.DAM, "extract": K.EXTRACT_LOG}
DISTRACTORS = ("crux", "analytics")
CALL_FILES = ("charter", "beacons", "sampling", "log", "eng", "runbook", "hosts", "notes")
ASK_FILES = ("img", "legacy", "avif", "contract", "dam")


def build(out, quiet=False):
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    p = lambda k: os.path.join(out, NAMES[k])
    W._CATALOGUES.clear()
    nov, eng = W.november_beacons(), W.engagement_beacons()
    ask = A.build()
    counts = {}
    counts[NAMES["beacons"]] = R.write_beacons(p("beacons"), nov)
    counts[NAMES["sampling"]] = R.write_sampling(p("sampling"))
    counts[NAMES["eng"]] = R.write_engagement_beacons(p("eng"), eng)
    counts[NAMES["hosts"]] = R.write_cdn_hosts(p("hosts"))
    counts[NAMES["crux"]] = R.write_crux(p("crux"), W.crux(nov))
    counts[NAMES["analytics"]] = R.write_analytics(p("analytics"), W.analytics())
    counts[NAMES["img"]] = R.write_image_logs(p("img"), ask["img"])
    counts[NAMES["legacy"]] = R.write_legacy_log(p("legacy"), ask["legacy"])
    counts[NAMES["dam"]] = R.write_dam(p("dam"), ask["dam"])
    R.write_change_log(p("log"))
    R.write_avif_table(p("avif"))
    R.write_extract_log(p("extract"), counts, NAMES)
    D.write_charter(p("charter"))
    D.write_contract(p("contract"))
    D.write_runbook(p("runbook"))
    D.write_notes(p("notes"), NAMES)
    PP.normalize_ooxml(p("log"), K.PEOPLE["lead"], K.PEOPLE["lead"], "2024-02-05T03:12:44Z", "2026-08-31T05:41:09Z",
                       excel=True)
    PP.normalize_ooxml(p("avif"), K.PEOPLE["lead"], K.PEOPLE["lead"], "2024-01-29T22:08:13Z", "2026-11-18T04:27:52Z",
                       excel=True)
    PP.normalize_pdf(p("charter"), b"D:20260720101544+10'00'", b"D:20260720102231+10'00'")
    PP.normalize_pdf(p("contract"), b"D:20260128163009+11'00'", b"D:20260129091447+11'00'")
    stamp = dt.datetime(2026, 12, 3, 13, 31, tzinfo=dt.timezone(dt.timedelta(hours=11))).timestamp()
    for f in os.listdir(out):
        os.utime(os.path.join(out, f), (stamp, stamp))
    if not quiet:
        print("built %s: %d files; %s" % (out, len(os.listdir(out)), ", ".join("%s %d" % kv for kv in counts.items())))
    return dict(counts=counts, dam_live=ask["dam_live"])


def digest(folder):
    return {f: hashlib.sha256(open(os.path.join(folder, f), "rb").read()).hexdigest() for f in sorted(os.listdir(folder))}


def cut_zip(root):
    import zipfile
    folder = os.path.join(root, "target")
    stamp = (2026, 12, 3, 13, 32, 10)
    zp = os.path.join(root, "target.zip")
    with zipfile.ZipFile(zp, "w") as z:
        for f in sorted(os.listdir(folder)):
            zi = zipfile.ZipInfo(f, date_time=stamp)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(folder, f), "rb").read())
    return zp


def write_metadata(path):
    meta = {"task": "task258", "distractor_files": [NAMES[k] for k in DISTRACTORS],
            "deliverables": list(K.DELIVERABLES),
            "call_files": [NAMES[k] for k in CALL_FILES], "ask_files": [NAMES[k] for k in ASK_FILES],
            "provenance": "Constructed records of a fictional Australian digital media group (declared): RUM "
                          "beacons, configuration, logs, a DAM export and documents generated by task258/generator; "
                          "the CrUX rows are constructed in the public dataset's layout; no third-party data."}
    with open(path, "w") as fh:
        json.dump(meta, fh, indent=2)
        fh.write("\n")


def everything(root, quiet=False):
    import deliver as G
    st = build(os.path.join(root, "target"), quiet=quiet)
    gold = os.path.join(root, "golden")
    if os.path.exists(gold):
        shutil.rmtree(gold)
    os.makedirs(gold)
    fig = G.compute(os.path.join(root, "target"))
    with open(os.path.join(root, "generator", "figures.json"), "w") as fh:
        json.dump(fig["figures"], fh, indent=1, sort_keys=True)
        fh.write("\n")
    G.write_note(os.path.join(gold, K.DELIVERABLES[0]), fig)
    G.write_chart(os.path.join(gold, K.DELIVERABLES[1]), fig)
    write_metadata(os.path.join(root, "metadata.json"))
    st["fig"] = fig
    return st


def main():
    import checks as CK
    import verify as V
    st = everything(TASK)
    CK.run(os.path.join(TASK, "target"), os.path.join(TASK, "golden"), st, os.path.join(TASK, "metadata.json"))
    V.main(os.path.join(TASK, "target"), os.path.join(TASK, "golden"))
    tmp = tempfile.mkdtemp(dir=TASK, suffix=".tmp")
    try:
        os.makedirs(os.path.join(tmp, "generator"))
        everything(tmp, quiet=True)
        same_t = digest(os.path.join(TASK, "target")) == digest(os.path.join(tmp, "target"))
        same_g = digest(os.path.join(TASK, "golden")) == digest(os.path.join(tmp, "golden"))
        same = {}
        for f in ("metadata.json", os.path.join("generator", "figures.json")):
            same[f] = open(os.path.join(TASK, f), "rb").read() == open(os.path.join(tmp, f), "rb").read()
        if not (same_t and same_g and all(same.values())):
            dt_, dg_ = digest(os.path.join(TASK, "target")), digest(os.path.join(tmp, "target"))
            gt_, gg_ = digest(os.path.join(TASK, "golden")), digest(os.path.join(tmp, "golden"))
            raise SystemExit("second build differs: target %s, golden %s, %s; files %s" % (
                same_t, same_g, same, [f for f in dt_ if dt_[f] != dg_.get(f)] + [f for f in gt_ if gt_[f] != gg_.get(f)]))
    finally:
        shutil.rmtree(tmp)
    allh = hashlib.sha256("".join(v for _, v in sorted(digest(os.path.join(TASK, "target")).items())).encode() +
                          "".join(v for _, v in sorted(digest(os.path.join(TASK, "golden")).items())).encode()).hexdigest()
    print("two builds byte-identical: %d target files, %d golden files, metadata.json and figures.json (sha256 %s)" % (
        len(os.listdir(os.path.join(TASK, "target"))), len(os.listdir(os.path.join(TASK, "golden"))), allh[:16]))
    import zipfile
    zp = cut_zip(TASK)
    with zipfile.ZipFile(zp) as z:
        inside = {i.filename: hashlib.sha256(z.read(i.filename)).hexdigest() for i in z.infolist()}
    if inside != digest(os.path.join(TASK, "target")):
        raise SystemExit("target.zip differs from target/")
    print("target.zip cut from this build: %d files, each identical to target/ (sha256 %s)" % (
        len(inside), hashlib.sha256(open(zp, "rb").read()).hexdigest()[:16]))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", help="build the pack only, into this folder")
    a = ap.parse_args()
    if a.out:
        build(a.out)
    else:
        main()
