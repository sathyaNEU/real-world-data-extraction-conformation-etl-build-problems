"""Cut target.zip from target/ and write metadata.json: members flat, in name order, with the export's timestamp,
every member's bytes asserted equal to the tree's file, so the archive is reproducible and never stale.

    python3 task191/generator/zipcut.py
"""
import hashlib
import json
import os
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from common import FILE_MTIME, TARGET, TASK  # noqa: E402

ZIP = os.path.join(TASK, "target.zip")

COVERS = {
    "adas_collision_warnings_2025-10_2026-10.csv": "the telematics platform's export of every driver-assistance camera warning on the fleet, 1 October 2025 to 1 November 2026",
    "fleetview_customer_bulletin_cb-2026-04.pdf": "the camera supplier's customer bulletin on forward camera firmware 2.3, April 2026",
    "fleet_register_2026.xlsx": "the fleet: models, camera firmware dates, depot allocations by date and registrations by date",
    "red_paradas_recorridos_2025_2026.xlsx": "the network's stops with coordinates and every line and direction's stop sequence, Red 2025 and Red 2026, with validity dates",
    "service_return_2025-10_2026-10.csv": "the monthly contract return: trips programmed and operated and kilometres by date, line and direction, October 2025 to October 2026",
    "driver_attention_programme_2027_terms.pdf": "the Driver-Attention Programme 2027's terms of reference",
    "red2026_service_notice.pdf": "the staff notice of the Red 2026 network change of 14 December 2025",
    "etm_logons_2026-10.csv": "the ticket machines' driver log-on sessions, 30 September to 1 November 2026",
    "hr_depot_assignments_2026.csv": "HR's depot assignment of every driver, with dates",
    "hr_hours_on_service_note.txt": "HR's note on hours on service for the duty and payroll returns",
    "incident_register_2026.xlsx": "the incident reports filed January to October 2026",
    "insurer_bordereau_2026-01_2026-10.csv": "the fleet insurer's month-end claims bordereau, January to October 2026",
    "broker_reporting_notes_2027_renewal.pdf": "the insurance broker's reporting notes for the 2027 renewal",
    "mobility_diversions_register_2026.csv": "the Mobility Department's register of authorised diversions, July to October 2026",
    "contract_annex_iv_kilometres.pdf": "the service contract's Annex IV on kilometres in service, working translation",
    "depot_absence_overtime_2026.xlsx": "each depot's drivers in post, sickness absence days and overtime hours by month, 2026",
    "boardings_by_line_2026.csv": "boardings by line and month, January to October 2026",
}
DISTRACTORS = ["target/depot_absence_overtime_2026.xlsx", "target/boardings_by_line_2026.csv"]


def cut():
    names = sorted(n for n in os.listdir(TARGET) if os.path.isfile(os.path.join(TARGET, n)) and not n.startswith("."))
    assert set(names) == set(COVERS), set(names) ^ set(COVERS)
    tmp = ZIP + ".tmp"
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as z:
        for n in names:
            zi = zipfile.ZipInfo(n, date_time=FILE_MTIME)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            with open(os.path.join(TARGET, n), "rb") as f:
                z.writestr(zi, f.read())
    os.replace(tmp, ZIP)
    with zipfile.ZipFile(ZIP) as z:
        assert z.namelist() == names, "archive members differ from target/"
        for n in names:
            assert z.read(n) == open(os.path.join(TARGET, n), "rb").read(), "stale member %s" % n
    sha = hashlib.sha256(open(ZIP, "rb").read()).hexdigest()
    meta = {
        "task": "task191",
        "decision": "Which depots of Lorvega's municipal bus company the 2027 Driver-Attention Programme runs at under "
                    "its terms, with each depot's collision-warning response and its at-fault collisions, claims, "
                    "kilometres in service and drivers' hours on service.",
        "deliverables": ["attention_programme_depots_2027.docx", "warning_response_by_depot_2026.xlsx",
                         "warning_response_2026.svg"],
        "distractor_files": DISTRACTORS,
        "files": {"target/" + n: {"source": "synthetic, generated by generator/build.py", "date": "2026-11-09",
                                  "license": "CC0-1.0", "covers": COVERS[n]} for n in names},
        "seed": "191_2026",
        "fictional": "Lorvega, Empresa Municipal de Autobuses de Lorvega, its depots, lines, streets, people, suppliers "
                     "and every record are fictional.",
    }
    with open(os.path.join(TASK, "metadata.json"), "w") as f:
        json.dump(meta, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print("target.zip: %d members, %d bytes, sha256 %s" % (len(names), os.path.getsize(ZIP), sha))
    return sha


if __name__ == "__main__":
    cut()
