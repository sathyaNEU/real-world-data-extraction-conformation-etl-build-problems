def walk(folder):
    out = []
    for root, dirs, files in os.walk(folder):
        dirs.sort()
        for f in files:
            out.append(os.path.relpath(os.path.join(root, f), folder))
    return sorted(out)


def stamp(folder):
    t = dt.datetime(*STAMP, tzinfo=dt.timezone.utc).timestamp()
    for f in walk(folder):
        os.utime(os.path.join(folder, f), (t, t))


def digest(folder):
    return {f: hashlib.sha256(open(os.path.join(folder, f), "rb").read()).hexdigest() for f in walk(folder)}


def cut_zip():
    zp = os.path.join(TASK, "target.zip")
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in walk(TARGET):
            zi = zipfile.ZipInfo(f, date_time=STAMP)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, open(os.path.join(TARGET, f), "rb").read())
    return zp


def fresh(folder):
    if os.path.isdir(folder):
        shutil.rmtree(folder)
    os.makedirs(folder, exist_ok=True)


def main(second=True, checks=True):
    fresh(TARGET)
    world = PK.build(TARGET)
    stamp(TARGET)
    TR.write(world, os.path.join(HERE, "truth.json"))
    fresh(GOLDEN)
    fig = FG.compute(TARGET)
    FG.write(fig, os.path.join(HERE, "figures.json"))
    GD.write(GOLDEN, fig)
    stamp(GOLDEN)
    WU.write(os.path.join(TASK, "submission.md"), fig)
    metadata(TARGET)
    if checks:
        import checks as C
        assert not C.main(TARGET)
    if second:
        tmp = tempfile.mkdtemp()
        t2, g2 = os.path.join(tmp, "target"), os.path.join(tmp, "golden")
        os.makedirs(t2)
        os.makedirs(g2)
        PK.build(t2)
        stamp(t2)
        GD.write(g2, FG.compute(t2))
        stamp(g2)
        d1, d2 = digest(TARGET), digest(t2)
        assert d1 == d2, [f for f in d1 if d1[f] != d2.get(f)]
        assert digest(GOLDEN) == digest(g2), [f for f in digest(GOLDEN) if digest(GOLDEN)[f] != digest(g2).get(f)]
        shutil.rmtree(tmp)
        zp = cut_zip()
        print("byte-identical; target.zip sha256", hashlib.sha256(open(zp, "rb").read()).hexdigest())
        import verify as V
        assert not V.main(zp)
    return fig


if __name__ == "__main__":
    main(second="--once" not in sys.argv, checks="--nochecks" not in sys.argv)
